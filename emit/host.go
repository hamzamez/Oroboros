// Imports accumulates what emitted functions need. A package-level sink is
// crude — the real answer is that each binding declares its import and the file
// writer collects them, which is g5's Tier 2 binding format arriving in the
// emitter by need rather than by design.
var Imports = map[string]bool{}

func contains(xs []string, s string) bool {
	for _, x := range xs {
		if x == s {
			return true
		}
	}
	return false
}

func mentions(t *core.Term, names []string) bool {
	switch t.Kind {
	case core.KName:
		return contains(names, t.Name)
	case core.KFn:
		return mentions(t.Body(), names)
	case core.KApp:
		for _, k := range t.Kids {
			if mentions(k, names) {
				return true
			}
		}
	}
	return false
}

func mangle(s string) string {
	var b strings.Builder
	upper := false
	for _, r := range s {
		switch {
		// `-` word break, `.` qualifier, `/` module path separator: all three
		// become camel-case boundaries so a qualified name is one host identifier.
		case r == '-' || r == '.' || r == '/':
			upper = true
		// `#` starts a name the READER generates and a program cannot write —
		// `match`'s loop variables, `values`' selector. It becomes `_` rather
		// than an escape so the emitted code is readable; a collision with a
		// user's `_m0` is resolved by openFresh like any other.
		case r == '#':
			b.WriteString("_")
		case r == '?':
			b.WriteString("P")
		case r == '!':
			b.WriteString("B")
		case unicode.IsLetter(r) || r == '_':
			if upper {
				b.WriteString(strings.ToUpper(string(r)))
				upper = false
			} else {
				b.WriteRune(r)
			}
		case unicode.IsDigit(r):
			b.WriteRune(r)
		default:
			fmt.Fprintf(&b, "U%04X", r)
		}
	}
	out := b.String()
	if out == "" || unicode.IsDigit(rune(out[0])) {
		out = "X" + out
	}
	if goKeywords[out] {
		out += "_"
	}
	return out
}

// export makes a legal name exported. Separate from mangle by design.
func export(s string) string {
	m := mangle(s)
	if m == "" {
		return m
	}
	return strings.ToUpper(m[:1]) + m[1:]
}

// goKeywords are Go's reserved words, which mangle suffixes with `_`.
var goKeywords = keywordSet(`break case chan const continue default defer else
	fallthrough for func go goto if import interface map package range return select
	struct switch type var`)

// File wraps emitted functions in a compilable Go file.
func File(pkg string, funcs map[string]string) string {
	names := make([]string, 0, len(funcs))
	for n := range funcs {
		names = append(names, n)
	}
	sort.Strings(names)

	var out strings.Builder
	out.WriteString("// Code generated by oroboros. DO NOT EDIT.\n\n")
	fmt.Fprintf(&out, "package %s\n\n", pkg)
	if len(Imports) > 0 {
		imps := make([]string, 0, len(Imports))
		for i := range Imports {
			imps = append(imps, i)
		}
		sort.Strings(imps)
		for _, i := range imps {
			fmt.Fprintf(&out, "import %q\n", i)
		}
		out.WriteString("\n")
	}
	for _, n := range names {
		out.WriteString(funcs[n])
		out.WriteString("\n")
	}
	return out.String()
}

// JSImports accumulates what emitted functions need, like the Go and Java
// sinks.
//
// IT DID NOT EXIST, AND THE FORMAT COULD ALREADY SAY IT. `(import …)` is one
// field of the shared target format; Go collects it, Java collects it, x86
// turns it into an extern — and JavaScript DROPPED it silently, because no
// target file had ever declared one. A path nothing runs is a path nothing
// checks, and this is that for a whole host: the first primitive on this target
// that needs a module could not have one.
