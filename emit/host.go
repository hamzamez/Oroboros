// jsKeywords are JavaScript's reserved words.
var jsKeywords = keywordSet(`await break case catch class const continue debugger
	default delete do else enum export extends false finally for function if implements
	import in instanceof interface let new null package private protected public return
	static super switch this throw true try typeof var void while with yield`)

// JSFile wraps emitted functions in an ES module.
func JSFile(funcs map[string]string) string {
	names := make([]string, 0, len(funcs))
	for n := range funcs {
		names = append(names, n)
	}
	sort.Strings(names)

	var out strings.Builder
	out.WriteString("// Code generated by oroboros. DO NOT EDIT.\n\n")
	for _, n := range names {
		out.WriteString(funcs[n])
		out.WriteString("\n")
	}
	return out.String()
}

// JavaImports accumulates what emitted methods need, like the Go sink.
var JavaImports = map[string]bool{}

// JavaRecords collects the record types generated for functions with several
// results, keyed by name so two functions with the same result shape share one.
var JavaRecords = map[string]string{}

func javaRecordName(tys []string) string {
	var b strings.Builder
	b.WriteString("Tup")
	for _, ty := range tys {
		b.WriteByte('_')
		for _, r := range ty {
			switch {
			case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9':
				b.WriteRune(r)
			case r == '[':
				b.WriteString("Arr")
			}
		}
	}
	return b.String()
}

