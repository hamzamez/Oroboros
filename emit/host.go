// Imports accumulates what emitted functions need. A package-level sink is
// crude — the real answer is that each binding declares its import and the file
// writer collects them, which is g5's Tier 2 binding format arriving in the
// emitter by need rather than by design.
var Imports = map[string]bool{}

// ResetImports empties the three import sets a program's printing fills. They
// are process-wide, and nothing cleared them: a command builds one program, so
// it never showed, but a process that builds two gave the second the first's
// imports, and Go refuses an import nothing uses (bufio-2026-10-01). A driver
// calls this before each program, so that what it emits is a function of that
// program alone. It empties every sink, not only the imports: Java's records
// and the assembly's data, externs and libraries are the same kind of state,
// and the first program's record and literals reached the second's file when
// only the imports were cleared (irtext-2026-10-04).
func ResetImports() {
	clear(Imports)
	clear(JSImports)
	clear(JavaImports)
	clear(JavaRecords)
	clear(LLVMImports)
	clear(LLVMStrings)
	clear(LLVMLibs)
}

// LLVMImports are the module lines an LLVM program's templates named (a
// `declare`, a global, a helper's `define`), each written once, and
// LLVMStrings its string literals' globals, keyed by content (ir/llvm,
// docs/spec/llvm.md §6). LLVMLibs are the libraries a used primitive names.
var (
	LLVMImports = map[string]bool{}
	LLVMStrings = map[string]string{}
	LLVMLibs    = map[string]bool{}
)

func contains(xs []string, s string) bool {
	for _, x := range xs {
		if x == s {
			return true
		}
	}
	return false
}

func mangle(s string) string {
	var b strings.Builder
	upper := false
	for _, r := range s {
		switch {
		// `-` word break, `.` qualifier, `/` module path separator: all three
		// become camel-case boundaries so a qualified name is one host identifier.
		case r == '-' || r == '.' || r == '/':
			upper = true
		// `#` starts a name the READER generates and a program cannot write —
		// `match`'s loop variables, `values`' selector. It becomes `_` rather
		// than an escape so the emitted code is readable; a collision with a
		// user's `_m0` is resolved by openFresh like any other.
		case r == '#':
			b.WriteString("_")
		case r == '?':
			b.WriteString("P")
		case r == '!':
			b.WriteString("B")
		case unicode.IsLetter(r) || r == '_':
			if upper {
				b.WriteString(strings.ToUpper(string(r)))
				upper = false
			} else {
				b.WriteRune(r)
			}
		case unicode.IsDigit(r):
			b.WriteRune(r)
		default:
			fmt.Fprintf(&b, "U%04X", r)
		}
	}
	out := b.String()
	if out == "" || unicode.IsDigit(rune(out[0])) {
		out = "X" + out
	}
	if goKeywords[out] {
		out += "_"
	}
	return out
}

// export makes a legal name exported. Separate from mangle by design.
func export(s string) string {
	m := mangle(s)
	if m == "" {
		return m
	}
	return strings.ToUpper(m[:1]) + m[1:]
}

// goKeywords are Go's reserved words, which mangle suffixes with `_`.
var goKeywords = keywordSet(`break case chan const continue default defer else
	fallthrough for func go goto if import interface map package range return select
	struct switch type var`)

// File wraps emitted functions in a compilable Go file.
func File(pkg string, funcs map[string]string) string {
	names := make([]string, 0, len(funcs))
	for n := range funcs {
		names = append(names, n)
	}
	sort.Strings(names)

	var out strings.Builder
	out.WriteString("// Code generated by oroboros. DO NOT EDIT.\n\n")
	fmt.Fprintf(&out, "package %s\n\n", pkg)
	if len(Imports) > 0 {
		imps := make([]string, 0, len(Imports))
		for i := range Imports {
			imps = append(imps, i)
		}
		sort.Strings(imps)
		for _, i := range imps {
			fmt.Fprintf(&out, "import %q\n", i)
		}
		out.WriteString("\n")
	}
	for _, n := range names {
		out.WriteString(funcs[n])
		out.WriteString("\n")
	}
	return out.String()
}

// JSImports accumulates what emitted functions need, like the Go and Java
// sinks.
//
// IT DID NOT EXIST, AND THE FORMAT COULD ALREADY SAY IT. `(import …)` is one
// field of the shared target format; Go collects it, Java collects it, x86
// turns it into an extern — and JavaScript DROPPED it silently, because no
// target file had ever declared one. A path nothing runs is a path nothing
// checks, and this is that for a whole host: the first primitive on this target
// that needs a module could not have one.
var JSImports = map[string]bool{}

// jsImportAlias names the namespace an import is bound to. `node:fs` becomes
// `fs`, which is what a template writes and what a person would write — the
// specifier is the module's ADDRESS and the alias is its NAME, and a target file
// should not have to repeat the second inside every template.
func jsImportAlias(spec string) string {
	if i := strings.LastIndexAny(spec, ":/"); i >= 0 {
		spec = spec[i+1:]
	}
	return jsMangle(spec)
}

