var PlantTableAttrWide bool

// PlantRangeAttrNarrow prints each range attribute one narrower, [lo, hi),
// so a function called at its set's top end computes with a poison value:
// TestARangeAttributeIsTheContract must see the answer change.
var PlantRangeAttrNarrow bool

// PlantNoRangeAttr prints none, the printer before φ's first kind.
var PlantNoRangeAttr bool

func (p *printer) retType() string {
	switch len(p.f.Results) {
	case 0:
		return "void"
	case 1:
		return p.llty(p.f.Results[0])
	}
	var ts []string
	for _, t := range p.f.Results {
		ts = append(ts, p.llty(t))
	}
	return "{ " + strings.Join(ts, ", ") + " }"
}

func (p *printer) ret(args []ir.V) {
	switch len(args) {
	case 0:
		p.line("ret void")
	case 1:
		p.line("ret %s %s", p.llty(p.f.Results[0]), p.as(args[0], p.llty(p.f.Results[0])))
	default:
		rt := p.retType()
		acc := "undef"
		for i, a := range args {
			r := "%" + p.fresh("r")
			p.line("%s = insertvalue %s %s, %s %s, %d", r, rt, acc, p.llty(p.f.Results[i]), p.as(a, p.llty(p.f.Results[i])), i)
			acc = r
		}
		p.line("ret %s %s", rt, acc)
	}
}

// ---------------------------------------------------------------- control

// target is where a yield, break or continue sends its arguments: the slots
// they are stored into and the block control passes to.
type target struct {
	slots []ir.V
	label string
}

// exits is what a region's terminators mean where it stands. A tabulate's
// body yields an element: stored at its index, then on to the next.
type exits struct {
	yield, brk, cont *target
	ret              bool
	tab              *tabulate
}

type tabulate struct {
	tab, idx ir.V
	next     string
}

func (p *printer) send(t *target, args []ir.V) {
	if t == nil {
		p.fail("a terminator with nowhere to go")
		return
	}
	for i, a := range args {
		ty := p.ty(t.slots[i])
		p.line("store %s %s, ptr %s", ty, p.asTo(a, ty, t.slots[i]), p.slot(t.slots[i]))
	}
	p.line("br label %%%s", t.label)
}

func (p *printer) region(r *ir.Region, x exits) {
	for i := range r.Stmts {
		p.stmt(&r.Stmts[i], x)
	}
	switch r.T {
	case ir.TYield:
		switch {
		case x.tab != nil:
			p.store(x.tab.tab, x.tab.idx, r.Args[0])
			p.line("br label %%%s", x.tab.next)
		case x.ret:
			p.ret(r.Args)
		default:
			p.send(x.yield, r.Args)
		}
	case ir.TBreak:
		p.send(x.brk, r.Args)
	case ir.TContinue:
		p.send(x.cont, r.Args)
	case ir.TBranch:
		if x.cont != nil && p.speculable(r.Then) && p.speculable(r.Else) {
			p.selects(r, x.cont)
			return
		}
		th, el := p.fresh("then"), p.fresh("else")
		p.line("br i1 %s, label %%%s, label %%%s", p.val(r.Cond), th, el)
		p.label(th)
		p.region(r.Then, x)
		p.label(el)
		p.region(r.Else, x)
	case ir.TUnreachable:
		p.line("unreachable")
	default:
		p.fail("terminator %s", r.T)
	}
}

// speculable reports an arm that goes round its loop computing only
// operations that are pure and have no undefined behaviour, only poison: so
// computing it when it is not taken changes nothing.
func (p *printer) speculable(r *ir.Region) bool {
	if r.T != ir.TContinue {
		return false
	}
	for i := range r.Stmts {
		s := &r.Stmts[i]
		switch s.Op {
		case ir.OConst, ir.OAdd, ir.OSub, ir.OMul, ir.ONeg, ir.OAnd, ir.OOr, ir.OXor, ir.ONot,
			ir.OEq, ir.ONe, ir.OLt, ir.OLe, ir.OGt, ir.OGe:
			if s.Mode == ir.MTrap {
				return false
			}
		default:
			return false
		}
	}
	return true
}

// selects prints a branch both of whose arms go round the loop as ONE back
// edge whose arguments are chosen (ADR 0080 item 2, backend-2026-10-26 §4):
// both arms computed, then a `select` per argument. Sound under poison, since
// `select` takes none from the operand it does not choose (LangRef), and the
// arms have no undefined behaviour to execute (speculable). Measured: the
// sieve's count of unmarked bytes, a branch that mispredicts on the primes'
// pattern, ran at 0.63 of MASM so and at 0.99 as a branch, which clang -O2 did
// not if-convert.
func (p *printer) selects(r *ir.Region, cont *target) {
	for _, arm := range []*ir.Region{r.Then, r.Else} {
		for i := range arm.Stmts {
			p.stmt(&arm.Stmts[i], exits{})
		}
	}
	for i := range r.Then.Args {
		ty := p.ty(cont.slots[i])
		a, b := p.asTo(r.Then.Args[i], ty, cont.slots[i]), p.asTo(r.Else.Args[i], ty, cont.slots[i])
		v := a
		if a != b {
			v = "%" + p.fresh("sel")
			p.line("%s = select i1 %s, %s %s, %s %s", v, p.val(r.Cond), ty, a, ty, b)
		}
		p.line("store %s %s, ptr %s", ty, v, p.slot(cont.slots[i]))
	}
	p.line("br label %%%s", cont.label)
}

// inner is the exits of a region an operation owns: its yield goes to the
// operation's results, a break or continue to the enclosing loop.
func inner(x exits, y *target) exits { return exits{yield: y, brk: x.brk, cont: x.cont} }

// ---------------------------------------------------------------- statements

func (p *printer) stmt(s *ir.Stmt, x exits) {
	switch s.Op {
	case ir.OConst, ir.OAssume, ir.OZero:
		// A literal is spelled where it is read; an assumption is the analyses'.
	case ir.OAdd, ir.OSub, ir.OMul, ir.ONeg, ir.ODiv, ir.ORem,
		ir.OAnd, ir.OOr, ir.OXor, ir.ONot, ir.OShl, ir.OShr, ir.OMod,
		ir.OEq, ir.ONe, ir.OLt, ir.OLe, ir.OGt, ir.OGe:
		if p.adder != nil && p.wide(s, func() bool { return p.adderStmt(s) }) {
			return
		}
		if p.readsDouble(s) {
			p.wide(s, func() bool { p.dop(s); return true })
			return
		}
		if p.narrow(s) {
			p.op(s) // at 32 bits: its operands and result are i32 (ADR 0127)
			return
		}
		p.wide(s, func() bool { p.op(s); return true })
	case ir.OCall:
		p.wide(s, func() bool { p.call(s); return true })
	case ir.OIndex:
		p.index(s)
	case ir.OLen:
		if p.s32(s.Res[0]) {
			// a length in S₃₂ (every one, on a triple whose address space is
			// 2³¹ bytes): the stored i64, truncated exactly
			n := "%" + p.fresh("len")
			p.line("%s = load i64, ptr %s", n, p.val(s.Args[0]))
			p.line("%%v%d = trunc i64 %s to i32", s.Res[0], n)
			return
		}
		p.line("%%v%d = load i64, ptr %s", s.Res[0], p.val(s.Args[0]))
	case ir.OStorage:
		// A table is its region here (llvm.md §4): the identity, as a no-op
		// address the optimizer folds.
		p.line("%%v%d = getelementptr i8, ptr %s, i64 0", s.Res[0], p.val(s.Args[0]))
	case ir.OSet:
		p.store(s.Args[0], s.Args[1], s.Args[2])
	case ir.OIf:
		th, el, join := p.fresh("then"), p.fresh("else"), p.fresh("join")
		p.line("br i1 %s, label %%%s, label %%%s", p.val(s.Args[0]), th, el)
		y := &target{slots: s.Res, label: join}
		p.label(th)
		p.region(s.Sub[0], inner(x, y))
		p.label(el)
		p.region(s.Sub[1], inner(x, y))
		p.label(join)
		p.load(s.Res)
	case ir.OLoop:
		body := s.Sub[0]
		head, exit := p.fresh("head"), p.fresh("exit")
		for i, a := range s.Args {
			ty := p.ty(body.Params[i])
			p.line("store %s %s, ptr %s", ty, p.asTo(a, ty, body.Params[i]), p.slot(body.Params[i]))
		}
		p.line("br label %%%s", head)
		p.label(head)
		p.load(body.Params)
		p.region(body, exits{brk: &target{slots: s.Res, label: exit}, cont: &target{slots: body.Params, label: head}})
		p.label(exit)
		p.load(s.Res)
	case ir.OBuild:
		buf := s.Sub[0].Params[0]
		p.names[buf] = p.table(buf, p.as(s.Args[0], "i64"), s.Store)
		done := p.fresh("built")
		p.region(s.Sub[0], inner(x, &target{slots: s.Res, label: done}))
		p.label(done)
		p.load(s.Res)
	case ir.OArray:
		t := p.table(s.Res[0], strconv.Itoa(len(s.Args)), s.Store)
		p.names[s.Res[0]] = t
		for i, a := range s.Args {
			p.storeAt(s.Res[0], strconv.Itoa(i), a)
		}
	case ir.OTabulate:
		p.tabulate(s, x)
	case ir.OCellRef, ir.OCellFresh, ir.OCellGet:
		p.wide(s, func() bool { p.cell(s); return true })
	default:
		p.fail("(%s …) is not printed on LLVM", s.Op)
	}
}

// cell prints a cell's statement at the word, in a wide scope (ADR 0127).
func (p *printer) cell(s *ir.Stmt) {
	if p.structCell(s) {
		return
	}
	switch s.Op {
	case ir.OCellRef, ir.OCellFresh:
		// A CELL A HOST WRITES IS A SLOT (ADR 0048 item 6, ADR 0112): f : X × T* →
		// R that keeps no address is X × T → R × T, so the reference is the
		// address of a fresh copy, an alloca of the cell's C type in the entry
		// block (Go's variable declared once at the top, for the same reason),
		// written here with the copy's value, or the type's zero.
		ll, trunc, _ := p.cellTy(p.f.Types[s.Res[0]])
		c := "%" + p.fresh("cell")
		p.allocas = append(p.allocas, fmt.Sprintf("  %s = alloca %s", c, ll))
		v := "0"
		if s.Op == ir.OCellRef {
			v = p.val(s.Args[0])
			if trunc {
				r := "%" + p.fresh("c")
				p.line("%s = trunc i64 %s to %s", r, v, ll)
				v = r
			}
		}
		p.line("store %s %s, ptr %s", ll, v, c)
		p.line("%%v%d = getelementptr i8, ptr %s, i64 0", s.Res[0], c)
	case ir.OCellGet:
		// WHAT THE HOST WROTE, read back at the cell's C type and embedded in
		// the word by its signedness, as a C result is (ADR 0094).
		ll, trunc, signed := p.cellTy(p.f.Types[p.pl.Res(s.Args[0])])
		from := p.val(s.Args[0])
		if PlantCellUnread {
			// the planted fault: a fresh slot holding 0, not the host's
			from = "%" + p.fresh("lost")
			p.allocas = append(p.allocas, fmt.Sprintf("  %s = alloca %s", from, ll))
			p.line("store %s 0, ptr %s", ll, from)
		}
		if !trunc {
			p.line("%%v%d = load %s, ptr %s", s.Res[0], ll, from)
			return
		}
		r := "%" + p.fresh("c")
		p.line("%s = load %s, ptr %s", r, ll, from)
		ext := "zext"
		if signed {
			ext = "sext"
		}
		p.line("%%v%d = %s %s %s to i64", s.Res[0], ext, ll, r)
	default:
		p.fail("(%s …) is not printed on LLVM", s.Op)
	}
}

// PlantCellUnread reads a cell back from a fresh slot holding 0, as if the
// host's write through the reference were lost: TestAnOutParameterIsACell must
// see GetFileSizeEx's size come back 0.
var PlantCellUnread bool

// cellTy is a cell's C type (ADR 0094's map on its element's set): its LLVM
// type, whether a value crosses by trunc, and whether it is signed.
func (p *printer) cellTy(t string) (string, bool, bool) {
	ll, cross, signed, ok := p.tg.CType(core.CellElem(t))
	if !ok || ll == "void" || ll == "ptr" {
		p.fail("a cell of %s has no C integer type on target %s (ADR 0112)", core.CellElem(t), p.tg.Name)
		return "i64", false, true
	}
	return ll, cross == "trunc", signed
}

var bigS128 = new(big.Int).Sub(new(big.Int).Lsh(big.NewInt(1), 127), big.NewInt(1))

// unsigned says v is held in the unsigned word: a natural below 2⁶⁴.
func (p *printer) unsigned(v ir.V) bool {
	ty := p.f.Types[v]
	return ty == "u64" || p.tg.ValueType(ty) == core.U64Type
}

// ends are a value's proven ends, exact, from its IR_P type or its literal;
// nil where unbounded.
func (p *printer) ends(v ir.V) (*big.Int, *big.Int) {
	if p.unsigned(v) {
		return big.NewInt(0), new(big.Int).SetUint64(1<<64 - 1)
	}
	if lo, hi, ok := core.IntRangeBig(p.f.Types[v]); ok {
		return lo, hi
	}
	if d := p.pl.Const[p.pl.Res(v)]; d != nil && d.Kind == core.KInt {
		return big.NewInt(d.Int), big.NewInt(d.Int)
	}
	return nil, nil
}

// readsDouble says s is an operation of the double word: it computes an
// intermediate there, or reads one back (ADR 0103).
func (p *printer) readsDouble(s *ir.Stmt) bool {
	if s.Mode == ir.MDouble {
		return true
	}
	for _, a := range s.Args {
		if p.dbl[a] || p.dbl[p.pl.Res(a)] {
			return true
		}
	}
	return false
}

// dop prints an operation of the double word (ADR 0103, llvm.md §3c) in
// i128: a word operand extended by its sign, an intermediate kept there, any
// other result truncated back to the word, a comparison an i1. Every
// intermediate is in E = (−2¹²⁶, 2¹²⁶), which the decision proved, so `nsw`
// holds of each, and `nuw` where the operands and the result are ≥ 0; a
// quotient, remainder or shift of a natural is LLVM's unsigned one.
func (p *printer) dop(s *ir.Stmt) {
	opnd := func(v ir.V) string {
		x := p.val(v)
		if p.dbl[v] || p.dbl[p.pl.Res(v)] || !strings.HasPrefix(x, "%") {
			return x // an intermediate, or a literal, the same spelling at i128
		}
		// a natural's zero and sign extensions agree, and `zext` says it is one:
		// the product of two is then one unsigned multiply
		ext := "sext"
		if p.lo(v) >= 0 {
			ext = "zext"
		}
		t := "%" + p.fresh("dw")
		p.line("%s = %s i64 %s to i128", t, ext, x)
		return t
	}
	args := make([]string, len(s.Args))
	for i, a := range s.Args {
		args[i] = opnd(a)
	}
	nat := func(v ir.V) bool { return p.lo(v) >= 0 }
	r := "%" + p.fresh("dr")
	if s.Mode == ir.MDouble {
		r = fmt.Sprintf("%%v%d", s.Res[0])
	}
	// THE FLAGS BY THE READING (ADR 0105): `nsw` where the result is inside
	// (−2¹²⁷, 2¹²⁷), an intermediate's by its proven range and a result back in
	// the word always; `nuw` where the operands and the result are naturals
	res := s.Res[0]
	lo, hi := p.ends(res)
	signedOK := s.Mode != ir.MDouble || lo != nil && hi != nil && lo.CmpAbs(bigS128) <= 0 && hi.CmpAbs(bigS128) <= 0
	natRes := s.Mode != ir.MDouble || lo != nil && lo.Sign() >= 0
	flags := func(nuw bool) string {
		f := []string{}
		if nuw && natRes || plantNuwFault {
			f = append(f, "nuw")
		}
		if signedOK {
			f = append(f, "nsw")
		}
		return strings.Join(f, " ")
	}
	switch s.Op {
	case ir.OAdd, ir.OMul:
		p.line("%s = %s %s i128 %s, %s", r, map[ir.Op]string{ir.OAdd: "add", ir.OMul: "mul"}[s.Op], flags(nat(s.Args[0]) && nat(s.Args[1])), args[0], args[1])
	case ir.OSub:
		// a − b leaves no unsigned wrap when 0 ≤ b ≤ a
		_, bh := p.ends(s.Args[1])
		al, _ := p.ends(s.Args[0])
		p.line("%s = sub %s i128 %s, %s", r, flags(nat(s.Args[1]) && al != nil && bh != nil && al.Cmp(bh) >= 0), args[0], args[1])
	case ir.ONeg:
		p.line("%s = sub %s i128 0, %s", r, flags(false), args[0])
	case ir.ODiv, ir.ORem:
		if d := p.pl.Const[p.pl.Res(s.Args[1])]; d == nil {
			// BY A WORD: the triple's 2-by-1 division on the dividend's halves,
			// its quotient proven in the word (llvm.md §3c)
			q, ok := p.tg.Prims[ir.TwoByOne]
			if !ok {
				p.fail("a quotient of the double word by a word, and no 2-by-1 division on target %s", p.tg.Name)
				return
			}
			lo, h, hi, qr := "%"+p.fresh("dl"), "%"+p.fresh("dh"), "%"+p.fresh("dhi"), "%"+p.fresh("dqr")
			p.line("%s = trunc i128 %s to i64", lo, args[0])
			p.line("%s = lshr i128 %s, 64", h, args[0])
			p.line("%s = trunc i128 %s to i64", hi, h)
			p.imports(q)
			p.line("%s = %s", qr, p.fillOps(q.Form, qr, []string{"i64 " + lo, "i64 " + hi, p.typed(s.Args[1])}))
			p.line("%%v%d = extractvalue { i64, i64 } %s, %d", s.Res[0], qr, map[ir.Op]int{ir.ODiv: 0, ir.ORem: 1}[s.Op])
			return
		}
		u := map[ir.Op]string{ir.ODiv: "udiv", ir.ORem: "urem"}[s.Op]
		if !nat(s.Args[0]) || !nat(s.Args[1]) {
			u = map[ir.Op]string{ir.ODiv: "sdiv", ir.ORem: "srem"}[s.Op]
		}
		p.line("%s = %s i128 %s, %s", r, u, args[0], args[1])
	case ir.OMod:
		// the Euclidean residue by a positive constant: urem of a natural, and
		// otherwise srem lifted into [0, m)
		if nat(s.Args[0]) {
			p.line("%s = urem i128 %s, %s", r, args[0], args[1])
			break
		}
		t, n, a := "%"+p.fresh("dm"), "%"+p.fresh("dn"), "%"+p.fresh("da")
		p.line("%s = srem i128 %s, %s", t, args[0], args[1])
		p.line("%s = icmp slt i128 %s, 0", n, t)
		p.line("%s = add nsw i128 %s, %s", a, t, args[1])
		p.line("%s = select i1 %s, i128 %s, i128 %s", r, n, a, t)
	case ir.OAnd:
		p.line("%s = and i128 %s, %s", r, args[0], args[1])
	case ir.OShr:
		sh := "ashr"
		if nat(s.Args[0]) {
			sh = "lshr"
		}
		p.line("%s = %s i128 %s, %s", r, sh, args[0], args[1])
	case ir.OEq, ir.ONe, ir.OLt, ir.OLe, ir.OGt, ir.OGe:
		pred := map[ir.Op]string{ir.OEq: "eq", ir.ONe: "ne", ir.OLt: "slt", ir.OLe: "sle", ir.OGt: "sgt", ir.OGe: "sge"}[s.Op]
		if nat(s.Args[0]) && nat(s.Args[1]) {
			// naturals, which may pass 2¹²⁷: the unsigned order
			pred = map[ir.Op]string{ir.OEq: "eq", ir.ONe: "ne", ir.OLt: "ult", ir.OLe: "ule", ir.OGt: "ugt", ir.OGe: "uge"}[s.Op]
		}
		p.line("%%v%d = icmp %s i128 %s, %s", s.Res[0], pred, args[0], args[1])
		return
	default:
		p.fail("(%s …) of the double word is not printed on LLVM", s.Op)
		return
	}
	if s.Mode != ir.MDouble {
		p.line("%%v%d = trunc i128 %s to i64", s.Res[0], r)
	}
}

// op is an integer operation, spelled by the target's form for it (plan.Form),
// with the flags the IR proved (llvm.md §5).
func (p *printer) op(s *ir.Stmt) {
	form := p.pl.Form(s)
	f := form[0]
	if s.Mode == ir.MTrap {
		f = form[1]
	}
	if f == "" {
		p.fail("the target has no spelling for (%s %s)", s.Op, s.Mode)
		return
	}
	if s.Mode == ir.MExact && !NoFlags {
		f = p.flags(s, f)
	}
	if !NoFlags {
		f = p.samesign(s, f)
	}
	p.expand(f, "expr", s.Res, s.Args)
}

// samesign is φ's second kind: LLVM's `icmp samesign`, which makes the result
// poison when the operands' signs differ, on a signed order whose operands
// the IR proves on one side of 0, both lo ≥ 0 or both hi < 0. Then a < b is
// the same relation read signed or unsigned, which is what the flag lets LLVM
// use. Ends are the IR_P types' and the literals' (lo, hi): a proven fact, so
// the flag adds no poison. Only the instruction that is the comparison, as
// `flags` does for arithmetic.
func (p *printer) samesign(s *ir.Stmt, f string) string {
	switch s.Op {
	case ir.OLt, ir.OLe, ir.OGt, ir.OGe:
	default:
		return f
	}
	if len(s.Args) != 2 || holes(f)['r'] || p.unsigned(s.Args[0]) || p.unsigned(s.Args[1]) {
		return f
	}
	word, rest, ok := strings.Cut(f, " ")
	if !ok || word != "icmp" || !strings.HasPrefix(rest, "s") {
		return f
	}
	a, b := s.Args[0], s.Args[1]
	nonneg := p.lo(a) >= 0 && p.lo(b) >= 0
	neg := p.hi(a) < 0 && p.hi(b) < 0
	if !(nonneg || neg || PlantSamesignAlways) || PlantNoSamesign {
		return f
	}
	return "icmp samesign " + rest
}

// PlantSamesignAlways writes samesign on every signed comparison, whatever its
// operands' signs: TestSamesignIsProvenOfItsOperands must see an answer change.
var PlantSamesignAlways bool

// PlantNoSamesign writes none, the printer before φ's second kind.
var PlantNoSamesign bool

// flags writes after an instruction's first word the flags the IR proved of
// this operation: `nsw`, the result inside the word, which is what `exact`
// means (ir.Decide); `nuw`, the same of the operands read as unsigned, from
// their proven ranges. `shl` takes them only where the bare instruction is the
// realization the IR chose, its count proven below 64 (ADR 0088). Only for the instruction that IS the operation: a form
// of several instructions (one naming its result) takes none.
func (p *printer) flags(s *ir.Stmt, f string) string {
	if holes(f)['r'] {
		return f
	}
	word, rest, ok := strings.Cut(f, " ")
	if !ok {
		return f
	}
	want := map[ir.Op]string{ir.OAdd: "add", ir.OSub: "sub", ir.OMul: "mul", ir.ONeg: "sub", ir.OShl: "shl"}[s.Op]
	if want == "" || word != want {
		return f
	}
	fl := "nsw"
	if plantNuwFault {
		return word + " nuw nsw " + rest
	}
	switch s.Op {
	case ir.OAdd, ir.OMul:
		if p.lo(s.Args[0]) >= 0 && p.lo(s.Args[1]) >= 0 {
			fl = "nuw nsw"
		}
	case ir.OShl:
		// a·2ᵏ inside the word with a ≥ 0 shifts out no set bit.
		if p.lo(s.Args[0]) >= 0 {
			fl = "nuw nsw"
		}
	case ir.OSub:
		// a − b leaves no unsigned wrap when 0 ≤ b ≤ a.
		if p.lo(s.Args[1]) >= 0 && p.lo(s.Args[0]) >= p.hi(s.Args[1]) {
			fl = "nuw nsw"
		}
	}
	return word + " " + fl + " " + rest
}

// lo and hi are a value's proven ends, from its IR_P type, ±∞ when unbounded.
func (p *printer) lo(v ir.V) float64 {
	if p.unsigned(v) {
		return 0
	}
	if lo, _, ok := core.IntRangeBig(p.f.Types[v]); ok && lo != nil {
		f, _ := new(big.Float).SetInt(lo).Float64()
		return f
	}
	if d := p.pl.Const[p.pl.Res(v)]; d != nil && d.Kind == core.KInt {
		return float64(d.Int)
	}
	return math.Inf(-1)
}

func (p *printer) hi(v ir.V) float64 {
	if _, hi, ok := core.IntRangeBig(p.f.Types[v]); ok && hi != nil {
		f, _ := new(big.Float).SetInt(hi).Float64()
		return f
	}
	if d := p.pl.Const[p.pl.Res(v)]; d != nil && d.Kind == core.KInt {
		return float64(d.Int)
	}
	return math.Inf(1)
}

func (p *printer) call(s *ir.Stmt) {
	q, ok := p.tg.Prims[s.Name]
	if !ok || (q.Kind != "expr" && q.Kind != "stmt") {
		p.fail("(call %s) has no template on target %s", s.Name, p.tg.Name)
		return
	}
	if q.CSym != "" {
		p.cCall(q, s)
		return
	}
	if q.Form == "" {
		p.fail("(call %s) is realized by a term, which reached the printer unsubstituted (ir.RealizeOps)", s.Name)
		return
	}
	p.imports(q)
	// A PROGRAM FUNCTION WITH NO RESULT (ADR 0113: a kept definition that
	// writes its lent buffer and answers ()): its call is `call void`, which
	// LLVM names nothing, and the unit the IR binds is read by nothing
	if q.Program && q.Result == "" && len(q.Results) == 0 {
		p.lines(p.fill(q.Form, "", s.Args))
		return
	}
	if len(s.Res) > 1 && q.Kind != "stmt" {
		// A HOST OPERATION INTO A PRODUCT B₁ × … × Bₙ answers LLVM's aggregate
		// { ρB₁, …, ρBₙ }, and each result is its projection: extractvalue j,
		// the product's universal property.
		var ts []string
		for _, v := range s.Res {
			ts = append(ts, p.ty(v))
		}
		agg := "%" + p.fresh("agg")
		ty := "{ " + strings.Join(ts, ", ") + " }"
		text := p.fill(q.Form, agg, s.Args)
		if holes(q.Form)['r'] {
			p.lines(text)
		} else {
			p.line("%s = %s", agg, text)
		}
		for j, v := range s.Res {
			p.line("%%v%d = extractvalue %s %s, %d", v, ty, agg, j)
		}
		return
	}
	p.expand(q.Form, q.Kind, s.Res, s.Args)
}

// cCall prints a C function's call by its prototype (ADR 0094, llvm.md §6a):
// out ∘ F ∘ (in × … × in), each map the C ABI's for the declared set on this
// triple. `trunc` is exact on a narrow integer's set and `sext`/`zext` its
// embedding back; a C string's bytes are at s + 8, NUL-ended (§4).
func (p *printer) cCall(q emit.Prim, s *ir.Stmt) {
	var ops, tys []string
	// in, ADR 0094's argument conversion: a parameter by its C type, a table
	// of bytes decayed to its first element (s + 8, after the length, llvm.md
	// §4), a C string the same address with its NUL past the bytes.
	param := func(i int) string {
		ll, cross, _, _ := p.tg.CType(q.Args[i])
		v := p.val(s.Args[i])
		// A STRUCT BY VALUE (ADR 0129): its fresh copy's bytes as the triple's
		// ABI passes an aggregate, measured against clang. x86-64 (Win64): one
		// of 1, 2, 4 or 8 bytes in a register as the integer of its bytes, any
		// other by the copy's address. i686: the bytes on the stack, `byval`,
		// which is what clang's expansion into i32s and its `byval` both are.
		if containsIdx(q.ByValue, i) && !PlantByValueAsPointer {
			lay, err := p.tg.Layout(core.CellElem(q.Args[i]))
			if err != nil {
				p.fail("%v", err)
				return "ptr " + v
			}
			if strings.HasPrefix(p.tg.Triple, "i686-") || strings.HasPrefix(p.tg.Triple, "i386-") {
				ty := fmt.Sprintf("ptr byval([%d x i8]) align 4", lay.Size)
				tys = append(tys, ty)
				return ty + " " + v
			}
			switch lay.Size {
			case 1, 2, 4, 8:
				ty := fmt.Sprintf("i%d", 8*lay.Size)
				r := "%" + p.fresh("c")
				p.line("%s = load %s, ptr %s, align 1", r, ty, v)
				tys = append(tys, ty)
				return ty + " " + r
			}
			tys = append(tys, "ptr")
			return "ptr " + v
		}
		switch cross {
		case "trunc":
			r := "%" + p.fresh("c")
			p.line("%s = trunc i64 %s to %s", r, v, ll)
			v = r
		case "cstr", "elems":
			r := "%" + p.fresh("c")
			p.line("%s = getelementptr inbounds i8, ptr %s, i64 8", r, v)
			v = r
		}
		tys = append(tys, ll)
		return ll + " " + v
	}
	if q.CArgs == nil {
		for i := range s.Args {
			ops = append(ops, param(i))
		}
	}
	// THE ARGUMENTS AS TERMS over the parameters: elem(b, lo) is &b[lo], the
	// decayed table offset by lo bytes, `inbounds` because the declaration's
	// `where` states lo <= len(b) (emit.boundsElem), so it lies in the region
	// or one past it; null is C's null pointer.
	for _, c := range q.CArgs {
		switch c.Kind {
		case emit.CParam:
			ops = append(ops, param(c.I))
		case emit.CElem:
			b := param(c.I)
			r := "%" + p.fresh("c")
			p.line("%s = getelementptr inbounds i8, %s, i64 %s", r, b, p.val(s.Args[c.J]))
			ops = append(ops, "ptr "+r)
		case emit.CNull:
			ops, tys = append(ops, "ptr null"), append(tys, "ptr")
		case emit.CRef:
			// &x: the struct's fresh copy, a reference, by its address (ADR 0130)
			ops = append(ops, param(c.I))
		case emit.CDiff:
			// hi − lo, a segment's length (ADR 0132), as the C integer of K bits
			r := "%" + p.fresh("c")
			p.line("%s = sub i64 %s, %s", r, p.val(s.Args[c.I]), p.val(s.Args[c.J]))
			ty := fmt.Sprintf("i%d", c.K)
			if c.K < 64 {
				t := "%" + p.fresh("c")
				p.line("%s = trunc i64 %s to %s", t, r, ty)
				r = t
			}
			ops, tys = append(ops, ty+" "+r), append(tys, ty)
		case emit.CLen:
			// len(s): the length the table holds at its address (§4), as the
			// C integer of J bits its `where` bounds it in (ADR 0132)
			r := "%" + p.fresh("c")
			p.line("%s = load i64, ptr %s, align 8", r, p.val(s.Args[c.I]))
			ty := fmt.Sprintf("i%d", c.J)
			if c.J < 64 {
				t := "%" + p.fresh("c")
				p.line("%s = trunc i64 %s to %s", t, r, ty)
				r = t
			}
			ops, tys = append(ops, ty+" "+r), append(tys, ty)
		}
	}
	ret, cross, signed := "void", "", false
	if q.Kind != "stmt" {
		ret, cross, signed, _ = p.tg.CType(q.Result)
	}
	// WHAT THE PROTOTYPE DOES NOT SAY, THE TRIPLE DOES: a DLL's function is
	// imported on Windows, and `stdcall` is a convention only on i686.
	storage, cc := "", ""
	if strings.Contains(p.tg.Triple, "-windows") {
		storage = "dllimport "
	}
	if q.CConv == "stdcall" && (strings.HasPrefix(p.tg.Triple, "i686-") || strings.HasPrefix(p.tg.Triple, "i386-")) {
		cc = "x86_stdcallcc "
	}
	emit.LLVMImports[fmt.Sprintf("declare %s%s%s @%s(%s)", storage, cc, ret, q.CSym, strings.Join(tys, ", "))] = true
	if q.Lib != "" {
		emit.LLVMLibs[q.Lib] = true
	}
	call := fmt.Sprintf("call %s%s @%s(%s)", cc, ret, q.CSym, strings.Join(ops, ", "))
	switch {
	case ret == "void" || len(s.Res) == 0:
		p.line("%s", call)
	case cross == "trunc":
		r := "%" + p.fresh("c")
		p.line("%s = %s", r, call)
		ext := "zext"
		if signed {
			ext = "sext"
		}
		p.line("%%v%d = %s %s %s to i64", s.Res[0], ext, ret, r)
	default:
		p.line("%%v%d = %s", s.Res[0], call)
	}
}

func (p *printer) imports(q emit.Prim) {
	if q.Import != "" {
		emit.LLVMImports[q.Import] = true
	}
	for _, x := range q.Externs {
		emit.LLVMImports[x] = true
	}
	if q.Lib != "" {
		emit.LLVMLibs[q.Lib] = true
	}
}

// expand prints one template (llvm.md §6). An expression's template is its
// instruction's right-hand side, unless it names its result, when it is the
// instructions themselves; a statement's is its instructions, and its value is
// its first argument (plan's alias).
func (p *printer) expand(form, kind string, res, args []ir.V) {
	dst := ""
	if kind != "stmt" && len(res) == 1 {
		dst = fmt.Sprintf("%%v%d", res[0])
	}
	text := p.fill(form, dst, args)
	if kind != "stmt" && !holes(form)['r'] {
		if dst == "" {
			p.fail("an expression template with no result")
			return
		}
		p.line("%s = %s", dst, text)
		return
	}
	p.lines(text)
}

// lines prints a filled template of several instructions, a label as a label.
func (p *printer) lines(text string) {
	for _, l := range strings.Split(text, "\n") {
		l = strings.TrimSpace(l)
		switch {
		case l == "":
		case strings.HasSuffix(l, ":") && !strings.ContainsAny(l, " ="):
			p.label(strings.TrimSuffix(l, ":"))
		default:
			p.line("%s", l)
		}
	}
}

// holes reports which kinds of hole a template has: 'r' its result.
func holes(form string) map[byte]bool {
	out := map[byte]bool{}
	for i := 0; i+1 < len(form); i++ {
		if form[i] != '%' {
			continue
		}
		i++
		out[form[i]] = true
	}
	return out
}

// fill expands a template's holes (core/jreadtarget.go's numbered holes): `%%`
// a `%`; `%r` the result; `%u` the expansion's number, `.N`; `%N` and `%{N}`
// operand N typed, `i64 %v3`; `%vN` its value alone.
func (p *printer) fill(form, dst string, args []ir.V) string {
	p.n++
	u := fmt.Sprintf(".%d", p.n)
	var b strings.Builder
	operand := func(i int) (int, int, bool) { // the operand number at form[i:], and its length
		if i < len(form) && form[i] == '{' {
			j := strings.IndexByte(form[i:], '}')
			if j < 0 {
				return 0, 0, false
			}
			n, err := strconv.Atoi(form[i+1 : i+j])
			return n, j + 1, err == nil
		}
		if i < len(form) && form[i] >= '1' && form[i] <= '9' {
			return int(form[i] - '0'), 1, true
		}
		return 0, 0, false
	}
	pick := func(n int) (ir.V, bool) {
		if n < 1 || n > len(args) {
			p.fail("template %q names operand %d of %d", form, n, len(args))
			return 0, false
		}
		return args[n-1], true
	}
	next := 0
	for i := 0; i < len(form); i++ {
		if form[i] != '%' || i+1 >= len(form) {
			b.WriteByte(form[i])
			continue
		}
		i++
		switch c := form[i]; {
		case c == '%':
			b.WriteByte('%')
		case c == 'r':
			// `%r0` is `%r` at arity one: a write-borrow's declaration names its
			// result after the handed-back buffer, which is the argument's own
			// storage (ADR 0070), so the call has one result (ADR 0112's ReadFile).
			b.WriteString(dst)
			if i+1 < len(form) && form[i+1] == '0' {
				i++
			}
		case c == 'u':
			b.WriteString(u)
		case c == 's':
			if v, ok := pick(next + 1); ok {
				b.WriteString(p.typed(v))
			}
			next++
		case c == 'v':
			if n, w, ok := operand(i + 1); ok {
				if v, ok := pick(n); ok {
					b.WriteString(p.val(v))
				}
				i += w
			} else {
				p.fail("template %q: %%v names no operand", form)
			}
		default:
			if n, w, ok := operand(i); ok {
				if v, ok := pick(n); ok {
					b.WriteString(p.typed(v))
				}
				i += w - 1
			} else {
				p.fail("template %q: %%%c is not a hole on LLVM", form, c)
			}
		}
	}
	return b.String()
}

// ---------------------------------------------------------------- tables

// table writes the length of a table of n elements for v's type into its
// storage: the value `alloc` answered, an operation of the IR on a target that
// realizes the allocator by a term (ADR 0092, ir/storage.go), or else the
// target's allocator template (emit.FindAlloc), zero on creation either way.
func (p *printer) table(v ir.V, n string, store []ir.V) string {
	if len(store) == 1 {
		t := p.val(store[0])
		p.line("store i64 %s, ptr %s", n, t)
		return t
	}
	q, ok := p.tg.FindAlloc()
	if !ok {
		p.fail("this target declares no allocator, so a table has no memory (docs/spec/tables.md §10)")
		return "null"
	}
	p.imports(q)
	if q.Form == "" {
		p.fail("a table has no storage: the allocator is a term, and ir.Storage gave this one none (ADR 0092)")
		return "null"
	}
	w := ir.ElemBytes(p.tg, p.f.Types[p.pl.Res(v)])
	bytes := "%" + p.fresh("n")
	p.line("%s = mul i64 %s, %d", bytes, n, w)
	total := "%" + p.fresh("n")
	p.line("%s = add i64 %s, 8", total, bytes)
	t := "%" + p.fresh("t")
	for _, l := range strings.Split(p.fillRaw(q.Form, t, "i64 "+total), "\n") {
		l = strings.TrimSpace(l)
		switch {
		case l == "":
		case strings.HasSuffix(l, ":") && !strings.ContainsAny(l, " ="):
			p.label(strings.TrimSuffix(l, ":"))
		case !holes(q.Form)['r']:
			p.line("%s = %s", t, l)
		default:
			p.line("%s", l)
		}
	}
	p.line("store i64 %s, ptr %s", n, t)
	return t
}

// fillOps fills a template whose operands are already spelled, typed: `%N`
// operand N, `%vN` its value alone, `%r` the result, `%u` the expansion's
// number.
func (p *printer) fillOps(form, dst string, ops []string) string {
	p.n++
	pairs := []string{"%%", "%", "%r", dst, "%u", fmt.Sprintf(".%d", p.n)}
	for i := len(ops); i >= 1; i-- {
		v := ops[i-1]
		pairs = append(pairs, fmt.Sprintf("%%v%d", i), v[strings.LastIndexByte(v, ' ')+1:], fmt.Sprintf("%%%d", i), v)
	}
	return strings.NewReplacer(pairs...).Replace(form)
}

// fillRaw fills a template whose one operand is already spelled.
func (p *printer) fillRaw(form, dst, op string) string {
	p.n++
	u := fmt.Sprintf(".%d", p.n)
	r := strings.NewReplacer("%%", "%", "%r", dst, "%u", u, "%v1", strings.TrimPrefix(op, "i64 "), "%1", op, "%s", op)
	return r.Replace(form)
}

// addr is the element i's address: past the 8-byte length, then i elements
// of the table's width. `inbounds` is the index's obligation, 0 ≤ i < len t,
// which the IR proved (refinements.md §3a: `-checked` never clears it).
func (p *printer) addr(tab ir.V, i, et string) string {
	d := "%" + p.fresh("d")
	inb := " inbounds"
	if NoFlags {
		inb = ""
	}
	p.line("%s = getelementptr%s i8, ptr %s, i64 8", d, inb, p.val(tab))
	e := "%" + p.fresh("e")
	p.line("%s = getelementptr%s %s, ptr %s, i64 %s", e, inb, et, d, i)
	return e
}

func (p *printer) index(s *ir.Stmt) {
	et, _ := p.elem(s.Args[0])
	e := p.addr(s.Args[0], p.as(s.Args[1], "i64"), et)
	res := fmt.Sprintf("%%v%d", s.Res[0])
	if et != "i8" {
		if et == "i64" && p.s32(s.Res[0]) {
			// a word element proven in S₃₂, truncated exactly (ADR 0127)
			w := "%" + p.fresh("ld")
			p.line("%s = load i64, ptr %s", w, e)
			p.line("%s = trunc i64 %s to i32", res, w)
			return
		}
		p.line("%s = load %s, ptr %s", res, et, e)
		return
	}
	b := "%" + p.fresh("b")
	p.line("%s = load i8, ptr %s", b, e)
	if p.ty(s.Res[0]) == "i1" {
		p.line("%s = icmp ne i8 %s, 0", res, b)
	} else {
		p.line("%s = zext i8 %s to %s", res, b, p.ty(s.Res[0]))
	}
}

func (p *printer) store(tab, i, v ir.V) { p.storeAt(tab, p.as(i, "i64"), v) }

// storeAt writes one element. A narrow one is narrowed: a Boolean widened to
// its byte, an integer truncated, exactly, since it is proven in the
// element's range.
func (p *printer) storeAt(tab ir.V, i string, v ir.V) {
	et, _ := p.elem(tab)
	e := p.addr(tab, i, et)
	x := p.val(v)
	switch {
	case et == "i8":
		z := "%" + p.fresh("z")
		if p.ty(v) == "i1" {
			p.line("%s = zext i1 %s to i8", z, x)
		} else {
			p.line("%s = trunc %s %s to i8", z, p.ty(v), x)
		}
		x = z
	case et == "i64":
		x = p.as(v, "i64") // an i32 element widened by its sign (ADR 0127)
	}
	p.line("store %s %s, ptr %s", et, x, e)
}

// tabulate is a rule's table: allocated, then each element stored by a loop
// over its indices, the body's yield its value.
func (p *printer) tabulate(s *ir.Stmt, x exits) {
	res, n, i := s.Res[0], s.Args[0], s.Sub[0].Params[0]
	t := p.table(res, p.as(n, "i64"), s.Store)
	p.names[res] = t
	// THE INDEX is held as its range is (ADR 0127): [0, len) is S₃₂'s on a
	// triple whose address space is 2³¹ bytes
	it := p.ty(i)
	cmpTy, iv := it, fmt.Sprintf("%%v%d", i)
	if it == "i32" && !p.s32(n) {
		cmpTy = "i64" // n may be 2³¹, which no i32 holds: compared at the word
	}
	bound := p.as(n, cmpTy)
	head, body, next, done := p.fresh("tab"), p.fresh("tabbody"), p.fresh("tabnext"), p.fresh("tabdone")
	p.line("store %s 0, ptr %s", it, p.slot(i))
	p.line("br label %%%s", head)
	p.label(head)
	p.load([]ir.V{i})
	c := "%" + p.fresh("c")
	if cmpTy != it {
		w := "%" + p.fresh("w")
		p.line("%s = sext i32 %s to i64", w, iv)
		iv = w
	}
	p.line("%s = icmp slt %s %s, %s", c, cmpTy, iv, bound)
	p.line("br i1 %s, label %%%s, label %%%s", c, body, done)
	p.label(body)
	p.region(s.Sub[0], exits{brk: x.brk, cont: x.cont, tab: &tabulate{tab: res, idx: i, next: next}})
	p.label(next)
	k := "%" + p.fresh("k")
	p.line("%s = add nuw nsw %s %%v%d, 1", k, it, i)
	p.line("store %s %s, ptr %s", it, k, p.slot(i))
	p.line("br label %%%s", head)
	p.label(done)
}

// Callees prints the program functions f calls (ADR 0101), each from a clone
// of its built function, so a cached callee is never changed: their LLVM
// definitions by name, and their IR_P functions for the program's text.
func Callees(tg *emit.Target, f *ir.Func) (map[string]string, []*ir.Func, error) {
	codes := map[string]string{}
	var funcs []*ir.Func
	for _, c := range ir.Callees(tg, f) {
		cl := c.Clone()
		code, err := FromFunc(tg, cl)
		if err != nil {
			return nil, nil, err
		}
		codes[cl.Name] = code
		funcs = append(funcs, cl)
	}
	return codes, funcs, nil
}

// CallbackWrapper is the function the host calls for the lifted function
// impl, whose definition def is (llvm.md §6c): at the claim's convention, its
// parameters C's types in C's order, each widened to the IR's type (zext for
// an unsigned C type, sext for a signed one), the call, and the result
// truncated to the C result's type.
func CallbackWrapper(tg *emit.Target, def, impl string, info ir.CallbackInfo) (string, error) {
	line, _, _ := strings.Cut(def, "\n")
	// cut at the function's own name: its result may carry an attribute with
	// parentheses of its own, `range(i64 …) i64 @f(`
	head, params, ok := strings.Cut(line, " "+Name(impl)+"(")
	if !ok || !strings.HasPrefix(head, "define ") {
		return "", fmt.Errorf("callback %s: no definition in %q", impl, line)
	}
	fs := strings.Fields(head)
	ret := fs[len(fs)-1]
	params, _, _ = strings.Cut(params, ") #")
	var tys []string
	depth, start := 0, 0
	for i := 0; i <= len(params); i++ {
		if i < len(params) && params[i] == '(' {
			depth++
		} else if i < len(params) && params[i] == ')' {
			depth--
		}
		if i == len(params) || params[i] == ',' && depth == 0 {
			if p := strings.Fields(params[start:i]); len(p) > 0 {
				tys = append(tys, p[0])
			}
			start = i + 1
		}
	}
	if len(tys) != len(info.CParams) {
		return "", fmt.Errorf("callback %s takes %d parameter(s), and its C signature %d", impl, len(tys), len(info.CParams))
	}
	cc := ""
	if info.Conv == "stdcall" && (strings.HasPrefix(tg.Triple, "i686-") || strings.HasPrefix(tg.Triple, "i386-")) {
		cc = "x86_stdcallcc "
	}
	var b strings.Builder
	var cps []string
	args := make([]string, len(tys))
	for k, c := range info.CParams {
		cps = append(cps, fmt.Sprintf("%s %%a%d", c.LL, k))
	}
	cret := info.CResult.LL
	fmt.Fprintf(&b, "define internal %s%s %s(%s) #0 {\nentry:\n", cc, cret, Name(impl+ir.WrapperSuffix), strings.Join(cps, ", "))
	for k, c := range info.CParams {
		i := info.Order[k]
		v := fmt.Sprintf("%%a%d", k)
		if c.LL != tys[i] {
			op := "zext"
			if c.Signed {
				op = "sext"
			}
			if c.LL == "ptr" || tys[i] == "ptr" {
				return "", fmt.Errorf("callback %s: parameter %d is %s in C and %s here", impl, i, c.LL, tys[i])
			}
			fmt.Fprintf(&b, "  %%b%d = %s %s %s to %s\n", k, op, c.LL, v, tys[i])
			v = fmt.Sprintf("%%b%d", k)
		}
		args[i] = tys[i] + " " + v
	}
	call := fmt.Sprintf("call %s %s(%s)", ret, Name(impl), strings.Join(args, ", "))
	switch {
	case cret == "void":
		fmt.Fprintf(&b, "  %s\n  ret void\n}\n", call)
	case cret == ret:
		fmt.Fprintf(&b, "  %%r = %s\n  ret %s %%r\n}\n", call, ret)
	default:
		fmt.Fprintf(&b, "  %%r = %s\n  %%c = trunc %s %%r to %s\n  ret %s %%c\n}\n", call, ret, cret, cret)
	}
	return b.String(), nil
}

// RuntimeEntry is a runtime function's entry at the symbol a code generator
// calls (ADR 0123): `define CC RET @"\01SYM"(…)`, calling the export def
// defines with its arguments. \01 keeps the symbol as written, with no `_`
// prefix or `@n` decoration, as LLVM's own libcalls are named. Only the types
// and names of def's parameters are read, so the entry is the export's
// function at another convention, and LLVM inlines the one into the other.
func RuntimeEntry(def, sym, cc string) (string, error) {
	line, _, _ := strings.Cut(def, "\n")
	head, params, ok := strings.Cut(line, "(")
	if !ok || !strings.HasPrefix(head, "define ") {
		return "", fmt.Errorf("runtime entry %s: no definition in %q", sym, line)
	}
	fs := strings.Fields(head)
	impl, ret := fs[len(fs)-1], fs[len(fs)-2]
	params, _, _ = strings.Cut(params, ") #")
	var tys, names []string
	depth, start := 0, 0
	for i := 0; i <= len(params); i++ {
		if i < len(params) && params[i] == '(' {
			depth++
		} else if i < len(params) && params[i] == ')' {
			depth--
		}
		if i == len(params) || params[i] == ',' && depth == 0 {
			p := strings.Fields(params[start:i])
			start = i + 1
			if len(p) == 0 {
				continue
			}
			tys, names = append(tys, p[0]), append(names, p[len(p)-1])
		}
	}
	args := make([]string, len(tys))
	for i := range tys {
		args[i] = tys[i] + " " + names[i]
	}
	a := strings.Join(args, ", ")
	return fmt.Sprintf("define %s %s @\"\\01%s\"(%s) #0 {\nentry:\n  %%r = call %s %s(%s)\n  ret %s %%r\n}\n",
		cc, ret, sym, a, ret, impl, a, ret), nil
}

// containsIdx reports i in xs.
func containsIdx(xs []int, i int) bool {
	for _, x := range xs {
		if x == i {
			return true
		}
	}
	return false
}

