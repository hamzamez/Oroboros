// NoFlags prints no flag at all (`-llvm-noflags`), for diagnosing a proof: a
// program whose answer changes with it has a flag its proof does not support.
var NoFlags bool

// plantNuwFault writes `nuw` on every proven add and sub, whatever their
// operands: the fault TestAFlagWithoutItsProofIsCaught plants.
var plantNuwFault bool

// FromFunc prints a lowered and DECIDED function: the step to IR_P, the
// verifier, and the printer.
func FromFunc(tg *emit.Target, f *ir.Func) (string, error) {
	if err := ir.ToP(tg, f); err != nil {
		return "", err
	}
	return Func(tg, f)
}

// Func prints one IR_P function as an LLVM `define`. The module lines its
// templates name go to emit.LLVMImports, which File writes.
func Func(tg *emit.Target, f *ir.Func) (string, error) {
	p := &printer{tg: tg, f: f, pl: plan.New(tg, f), slots: map[ir.V]string{}, names: map[ir.V]string{}, dbl: ir.Doubles(f), wideNow: map[ir.V]bool{}}
	p.adders()
	out := p.function()
	if p.err != nil {
		return "", fmt.Errorf("%s: %w", f.Name, p.err)
	}
	// A CALLBACK'S WRAPPER (ADR 0133, llvm.md §6c): the function the host
	// calls, at the claim's convention and C's types, printed with the
	// function it calls from the claim the text names
	if f.Callback != "" {
		info, err := ir.CallbackSignature(tg, f.Callback)
		if err != nil {
			return "", fmt.Errorf("%s: %w", f.Name, err)
		}
		w, err := CallbackWrapper(tg, out, f.Name, info)
		if err != nil {
			return "", err
		}
		out += "\n" + w
	}
	return out, nil
}

// Name is a function's LLVM name: its IR name with `-` made `_` (llvm.md §8),
// so a C driver can name it, and quoted where it holds anything else.
func Name(n string) string {
	n = strings.ReplaceAll(n, "-", "_")
	for _, c := range n {
		if !(c == '_' || c == '.' || c == '$' || c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= '0' && c <= '9') {
			return "@" + strconv.Quote(n)
		}
	}
	return "@" + n
}

// File writes a module: the target's triple (ADR 0093 item 5), the module lines
// the functions' templates named, their string literals, the functions, and,
// for an entry point, `main`, which calls it. The entry never returns: the
// driver composes it with Σ_OS's exit (cmd/build), so the process ends by the
// operating system's own call, which the OS layer defines.
func File(tg *emit.Target, funcs map[string]string, entry string) string {
	var b strings.Builder
	b.WriteString("; Code generated by oroboros. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "target triple = %q\n\n", tg.Triple)
	lines := make([]string, 0, len(emit.LLVMImports))
	for l := range emit.LLVMImports {
		lines = append(lines, l)
	}
	// Declarations and globals first, then helper definitions, each sorted, so
	// the module is a function of the program.
	sort.Slice(lines, func(i, j int) bool {
		di, dj := strings.HasPrefix(lines[i], "define"), strings.HasPrefix(lines[j], "define")
		if di != dj {
			return dj
		}
		return lines[i] < lines[j]
	})
	strs := make([]string, 0, len(emit.LLVMStrings))
	for s, name := range emit.LLVMStrings {
		// A STRING CARRIES A NUL AFTER ITS BYTES (llvm.md §4), outside its length.
		strs = append(strs, fmt.Sprintf("%s = private unnamed_addr constant { i64, [%d x i8] } { i64 %d, [%d x i8] c\"%s\\00\" }, align 8",
			name, len(s)+1, len(s), len(s)+1, cbytes(s)))
	}
	sort.Strings(strs)
	for _, l := range lines {
		if !strings.HasPrefix(l, "define") {
			b.WriteString(l + "\n")
		}
	}
	for _, s := range strs {
		b.WriteString(s + "\n")
	}
	b.WriteString("\n")
	for _, l := range lines {
		if strings.HasPrefix(l, "define") {
			b.WriteString(l + "\n\n")
		}
	}
	names := make([]string, 0, len(funcs))
	for n := range funcs {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		fn := funcs[n]
		// A MODULE WITH NO ENTRY POINT IS A LIBRARY a driver links (the
		// gauntlet's harnesses), so its functions are external; beside an
		// entry point they are internal, which lets LLVM drop and specialize.
		if entry == "" {
			fn = strings.Replace(fn, "define internal ", "define ", 1)
		}
		b.WriteString(fn)
		b.WriteString("\n")
	}
	if entry != "" {
		// The entry point's value is discarded, as Go's `func main` discards
		// it; its type is read off its own definition.
		rt := "void"
		if def, _, ok := strings.Cut(funcs[entry], " "+Name(entry)+"("); ok {
			rt = strings.TrimPrefix(def, "define internal ")
		}
		call := fmt.Sprintf("call %s %s()", rt, Name(entry))
		if rt != "void" {
			call = "%r = " + call
		}
		fmt.Fprintf(&b, "define void @main() #0 {\nentry:\n  %s\n  unreachable\n}\n\n", call)
	}
	// nounwind: nothing of ours unwinds (a crash is Σ_OS's exit or a trap), so
	// no unwind tables. "no-builtins": no loop is rewritten into a call to the C
	// runtime's memset or memcpy, which this target does not link (llvm.md §2).
	b.WriteString("attributes #0 = { nounwind \"no-builtins\" }\n")
	return b.String()
}

// cbytes is a string's bytes in LLVM's c"…" notation: printable ASCII as
// itself, every other byte, `"` and `\` as \XX.
func cbytes(s string) string {
	var b strings.Builder
	for i := 0; i < len(s); i++ {
		c := s[i]
		if c >= 0x20 && c < 0x7f && c != '"' && c != '\\' {
			b.WriteByte(c)
		} else {
			fmt.Fprintf(&b, "\\%02X", c)
		}
	}
	return b.String()
}

type printer struct {
	tg      *emit.Target
	f       *ir.Func
	pl      *plan.Plan
	b       strings.Builder
	allocas []string
	slots   map[ir.V]string // a joined value's alloca
	names   map[ir.V]string // a value spelled other than %vN: a new table's pointer
	dbl     map[ir.V]bool   // the values held in the double word, i128 (ADR 0103)
	// wideNow are the values a wide scope holds at the word (scalar.go, ADR 0127)
	wideNow map[ir.V]bool
	// the full adders (ADR 0108, carry.go): a top statement's result → its
	// adder, and the inner sums they absorb
	adder    map[ir.V]*adder
	absorbed map[*ir.Stmt]bool
	n        int
	err      error
}

func (p *printer) fail(format string, args ...any) {
	if p.err == nil {
		p.err = fmt.Errorf(format, args...)
	}
}

func (p *printer) line(format string, args ...any) {
	p.b.WriteString("  " + fmt.Sprintf(format, args...) + "\n")
}

func (p *printer) label(l string) { p.b.WriteString(l + ":\n") }

// fresh is a name the printer makes. It begins with `.`, which no IR value's
// name (%vN) and no template's (a stem, then `${#}`'s `.N`) does.
func (p *printer) fresh(stem string) string { p.n++; return fmt.Sprintf(".%s%d", stem, p.n) }

// ---------------------------------------------------------------- types

// llty is the LLVM type of a value of IR_P type t (llvm.md §3).
func (p *printer) llty(t string) string {
	switch {
	case core.IsCell(t):
		return "ptr" // a cell is its slot's address (ADR 0048, 0112)
	case t == "bool":
		return "i1"
	case t == "string", ir.ElemOf(p.tg, t) != "":
		return "ptr"
	}
	if _, _, ok := core.IntRangeBig(t); ok || core.UnboundedRange(t) {
		return "i64" // an integer held in the word, its range a fact
	}
	switch p.tg.ValueType(t) {
	case "int":
		return "i64"
	case "bool":
		return "i1"
	case "f64":
		return "double"
	case "string":
		return "ptr"
	}
	switch h := p.tg.HostType(t); h {
	case "i64", "i1", "double", "ptr":
		return h
	}
	p.fail("type %s has no LLVM type on target %s", t, p.tg.Name)
	return "i64"
}

func (p *printer) ty(v ir.V) string {
	if p.s32(v) {
		return "i32" // ρ₃₂ of its range (scalar.go, ADR 0127)
	}
	return p.llty(p.f.Types[v])
}

// elem is a table's element type in memory: an i8 for a Boolean or a range
// the target holds in a byte, a double, a pointer for a table or a string, and
// the word otherwise (llvm.md §4). It is read off the table's representative,
// as ir/x86 reads it.
func (p *printer) elem(tab ir.V) (string, string) {
	t := p.f.Types[p.pl.Res(tab)]
	e := ir.ElemOf(p.tg, t)
	if e == "" {
		p.fail("%s is not a table", t)
		return "i64", ""
	}
	// ONE LAYOUT (ir.ElemBytes): the bytes an element takes, which the table's
	// storage was allocated by.
	if ir.ElemBytes(p.tg, t) == 1 {
		return "i8", e
	}
	return p.llty(e), e
}

// ---------------------------------------------------------------- values

// val is a value's spelling as an operand: its representative's register, a
// literal, or a zero.
func (p *printer) val(v ir.V) string {
	r := p.pl.Res(v)
	if s, ok := p.names[r]; ok {
		return s
	}
	if d := p.pl.Const[r]; d != nil {
		return p.lit(d, p.ty(r))
	}
	if p.pl.Zero[r] {
		switch p.ty(r) {
		case "ptr":
			return "null"
		case "i1":
			return "false"
		case "double":
			return "0.0"
		}
		return "0"
	}
	return fmt.Sprintf("%%v%d", r)
}

func (p *printer) typed(v ir.V) string { return p.ty(v) + " " + p.val(v) }

func (p *printer) lit(d *core.Term, ty string) string {
	switch d.Kind {
	case core.KBool:
		if d.IsTrue() {
			return "true"
		}
		return "false"
	case core.KStr:
		return p.str(d.Str)
	case core.KDec:
		f, _ := d.Dec.Float64()
		return fmt.Sprintf("0x%016X", math.Float64bits(f))
	case core.KInt:
		if ty == "double" {
			return fmt.Sprintf("0x%016X", math.Float64bits(float64(d.Int)))
		}
		return strconv.FormatInt(d.Int, 10)
	}
	if v, ok := new(big.Int).SetString(d.String(), 10); ok && v.IsInt64() {
		return v.String()
	}
	p.fail("literal %s has no LLVM spelling", core.ShowTerm(d))
	return "0"
}

// str is a string literal's global, a table of its UTF-8 bytes, one per
// distinct content in the module.
func (p *printer) str(s string) string {
	if n, ok := emit.LLVMStrings[s]; ok {
		return n
	}
	n := fmt.Sprintf("@.str.%d", len(emit.LLVMStrings))
	emit.LLVMStrings[s] = n
	return n
}

func (p *printer) slot(v ir.V) string {
	if s, ok := p.slots[v]; ok {
		return s
	}
	s := "%" + p.fresh("s")
	p.slots[v] = s
	p.allocas = append(p.allocas, fmt.Sprintf("  %s = alloca %s", s, p.ty(v)))
	return s
}

// load reads each joined value from its slot, where control arrives.
func (p *printer) load(vs []ir.V) {
	for _, v := range vs {
		p.line("%%v%d = load %s, ptr %s", v, p.ty(v), p.slot(v))
	}
}

// ---------------------------------------------------------------- the function

func (p *printer) function() string {
	var params []string
	for _, v := range p.f.Params {
		params = append(params, fmt.Sprintf("%s%s%s %%v%d", p.llty(p.f.Types[v]), p.rangeAttr(p.f.Types[v]), p.tableAttr(p.f.Types[v], true), v))
		// A PARAMETER IN S₃₂ is the word at the boundary and an i32 inside it
		// (ADR 0127): narrowed once, exactly, at entry
		if p.s32(v) {
			n := fmt.Sprintf("%%v%d.n", v)
			p.line("%s = trunc i64 %%v%d to i32", n, v)
			p.names[v] = n
		}
	}
	ret := p.retType()
	if len(p.f.Results) == 1 {
		if a := p.rangeAttr(p.f.Results[0]) + p.tableAttr(p.f.Results[0], false); a != "" {
			ret = a[1:] + " " + ret
		}
	}
	p.region(p.f.Body, exits{ret: true})
	var out strings.Builder
	fmt.Fprintf(&out, "define internal %s %s(%s) #0 {\nentry:\n", ret, Name(p.f.Name), strings.Join(params, ", "))
	for _, a := range p.allocas {
		out.WriteString(a + "\n")
	}
	out.WriteString(p.b.String())
	out.WriteString("}\n")
	return out.String()
}

// rangeAttr is φ's first kind (φ maximal, assessment-2026-11-16 item 5):
// LLVM's `range(i64 a, b)` attribute, the half-open [a, b), on a parameter or
// a result whose IR_P type is a range lo..hi narrower than the word, a = lo and
// b = hi + 1 (wrapping at 2⁶³, so [0, 2⁶³) is `range(i64 0, -2^63)`).
//
// THEOREM (the attribute is the contract). A function the printer prints is a
// kept definition or a library instance (ADR 0101, 0113); its parameters' types
// are its contract's sets S ∩ W, assumed in the body and proven at every call,
// or the call is inlined (P4, ADR 0102), and its result's type is the claim
// ADR 0072 decides at the definition. So every value a parameter or the result
// takes lies in lo..hi: an argument or a return outside it, which `range` makes
// poison, never occurs. ∎ An unsigned word, a Boolean, a pointer or the whole
// word has no attribute: it says nothing a type does not.
func (p *printer) rangeAttr(ty string) string {
	if PlantNoRangeAttr {
		return ""
	}
	lo, hi, ok := core.IntRangeBig(ty)
	if !ok || p.llty(ty) != "i64" || p.tg.ValueType(ty) == core.U64Type {
		return ""
	}
	min := new(big.Int).Lsh(big.NewInt(1), 63)
	min.Neg(min)
	max := new(big.Int).Sub(new(big.Int).Neg(min), big.NewInt(1))
	if lo.Cmp(min) < 0 || hi.Cmp(max) > 0 || (lo.Cmp(min) == 0 && hi.Cmp(max) == 0) {
		return ""
	}
	b := new(big.Int).Add(hi, big.NewInt(1))
	if PlantRangeAttrNarrow {
		b.Sub(b, big.NewInt(1)) // [lo, hi): the set's top end left out
	}
	if b.Cmp(max) > 0 {
		b = min // hi = 2⁶³ − 1: [lo, 2⁶³) wraps to the word's least
	}
	if b.Cmp(lo) == 0 {
		return "" // empty under the fault: LLVM refuses an empty range
	}
	return fmt.Sprintf(" range(i64 %s, %s)", lo, b)
}

// tableAttr is φ's third kind: `nonnull dereferenceable(8) align 8` on a
// parameter or result that is a table or a string.
//
// THEOREM (a table's pointer is a region's). A table or string value is the
// address of one of: a region `region`/`region_raw` answered, which traps on
// null and holds n·w + 8 bytes and the zero byte past them (ADR 0092, 0117),
// 8-aligned by HeapAlloc and VirtualAlloc; a token's region handed to `reuse`,
// the same; or a string literal's global, `{ i64, [n x i8] }` with its NUL,
// `align 8`. Each is non-null, 8-aligned, and holds at least its 8-byte
// length, so `dereferenceable(8)` reads only the length's word. A segment is
// a rule, never a pointer into a region's interior at a boundary (a segment at
// a kept boundary is not built, ADR 0113), and a dead region's token, which
// may be null, is a loop's variable, never a function's parameter. ∎ A cell,
// a raw `ptr` (a Win32 handle) and anything else take no attribute.
func (p *printer) tableAttr(ty string, param bool) string {
	if PlantNoTableAttr || p.llty(ty) != "ptr" || core.IsCell(ty) {
		return ""
	}
	if ty != "string" && ir.ElemOf(p.tg, ty) == "" {
		return ""
	}
	n := 8
	if PlantTableAttrWide {
		n = 4096 // past every region of a short table: LLVM may load there
	}
	// φ's fourth kind: A LENT BUFFER IS `noalias` (ADR 0018, 0070). R2 hands a
	// buffer to one call once, so no other argument names its region; a table
	// frozen from it is no longer a buffer (R3), and the callee's other
	// pointers are its own allocations. So during the call its region is
	// reached only through this parameter, which is LLVM's noalias.
	// ON A PARAMETER ONLY. On a result noalias says the pointer is fresh, as
	// malloc's is, and a definition that lends a buffer may hand it back (an
	// export returns its lent buffer, smooth_into): the caller's own pointer
	// and the result are then one region, which the flag would deny.
	na := ""
	if strings.HasPrefix(ty, "buffer") && (param || PlantNoaliasResult) && !PlantNoNoalias {
		na = " noalias"
	}
	return fmt.Sprintf("%s nonnull dereferenceable(%d) align 8", na, n)
}

