// Package llvm prints IR_P as LLVM IR (ADR 0080, docs/spec/llvm.md): h_L, a map
// from the IR's text to a module clang compiles. It is the native targets'
// printer, beside ir/x86's MASM until that retires at parity (ADR 0080 item 5).
//
// THE PRINTER STATES THE IR'S PROOFS, AND ONLY THEM (llvm.md §1). LLVM adds no
// check: an instruction with a flag (`nsw`, `nuw`, `inbounds`) is poison outside
// the domain the flag asserts, so each flag is written only where the IR proved
// the operands inside it. The decision's modes and IR_P's types are those
// proofs: an `exact` operation is proven inside the word, a π's type holds on its
// arm (W6, pijustified-2026-11-02), an index is proven in bounds.
//
// A VALUE IS A REGISTER, A JOIN IS A SLOT (llvm.md §7). An operation's result is
// the SSA register %vN, N its IR number; a region's parameters and the results
// of an `if`, `loop`, `build` or `tabulate` are `alloca`s, stored where control
// passes to them and loaded where it arrives. clang's mem2reg makes them φs, the
// front end's idiom: SSA construction is LLVM's (Cytron et al. 1991), and the
// structured regions give it a reducible graph.
package llvm

import (
	"fmt"
	"math"
	"math/big"
	"sort"
	"strconv"
	"strings"

	"oroboros/core"
	"oroboros/emit"
	"oroboros/ir"
	"oroboros/ir/plan"
)

// Triple is the target triple every module is printed for (ADR 0080 item 3:
// 32-bit is another triple, not built).
const Triple = "x86_64-pc-windows-msvc"

// NoFlags prints no flag at all (`-llvm-noflags`), for diagnosing a proof: a
// program whose answer changes with it has a flag its proof does not support.
var NoFlags bool

// plantNuwFault writes `nuw` on every proven add and sub, whatever their
// operands: the fault TestAFlagWithoutItsProofIsCaught plants.
var plantNuwFault bool

// FromFunc prints a lowered and DECIDED function: the step to IR_P, the
// verifier, and the printer.
func FromFunc(tg *emit.Target, f *ir.Func) (string, error) {
	if err := ir.ToP(tg, f); err != nil {
		return "", err
	}
	return Func(tg, f)
}

// Func prints one IR_P function as an LLVM `define`. The module lines its
// templates name go to emit.LLVMImports, which File writes.
func Func(tg *emit.Target, f *ir.Func) (string, error) {
	p := &printer{tg: tg, f: f, pl: plan.New(tg, f), slots: map[ir.V]string{}, names: map[ir.V]string{}}
	out := p.function()
	if p.err != nil {
		return "", fmt.Errorf("%s: %w", f.Name, p.err)
	}
	return out, nil
}

// Name is a function's LLVM name: its IR name with `-` made `_` (llvm.md §8),
// so a C driver can name it, and quoted where it holds anything else.
func Name(n string) string {
	n = strings.ReplaceAll(n, "-", "_")
	for _, c := range n {
		if !(c == '_' || c == '.' || c == '$' || c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= '0' && c <= '9') {
			return "@" + strconv.Quote(n)
		}
	}
	return "@" + n
}

// File writes a module: the triple, the module lines the functions' templates
// named, their string literals, the functions, and, for an entry point, `main`,
// which calls it and ends the process (Win32 has no runtime to return to).
func File(tg *emit.Target, funcs map[string]string, entry string) string {
	if entry != "" {
		emit.LLVMImports["declare dllimport void @ExitProcess(i32)"] = true
	}
	var b strings.Builder
	b.WriteString("; Code generated by oroboros. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "target triple = %q\n\n", Triple)
	lines := make([]string, 0, len(emit.LLVMImports))
	for l := range emit.LLVMImports {
		lines = append(lines, l)
	}
	// Declarations and globals first, then helper definitions, each sorted, so
	// the module is a function of the program.
	sort.Slice(lines, func(i, j int) bool {
		di, dj := strings.HasPrefix(lines[i], "define"), strings.HasPrefix(lines[j], "define")
		if di != dj {
			return dj
		}
		return lines[i] < lines[j]
	})
	strs := make([]string, 0, len(emit.LLVMStrings))
	for s, name := range emit.LLVMStrings {
		strs = append(strs, fmt.Sprintf("%s = private unnamed_addr constant { i64, [%d x i8] } { i64 %d, [%d x i8] c\"%s\" }, align 8",
			name, len(s), len(s), len(s), cbytes(s)))
	}
	sort.Strings(strs)
	for _, l := range lines {
		if !strings.HasPrefix(l, "define") {
			b.WriteString(l + "\n")
		}
	}
	for _, s := range strs {
		b.WriteString(s + "\n")
	}
	b.WriteString("\n")
	for _, l := range lines {
		if strings.HasPrefix(l, "define") {
			b.WriteString(l + "\n\n")
		}
	}
	names := make([]string, 0, len(funcs))
	for n := range funcs {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		fn := funcs[n]
		// A MODULE WITH NO ENTRY POINT IS A LIBRARY a driver links (the
		// gauntlet's harnesses), so its functions are external; beside an
		// entry point they are internal, which lets LLVM drop and specialize.
		if entry == "" {
			fn = strings.Replace(fn, "define internal ", "define ", 1)
		}
		b.WriteString(fn)
		b.WriteString("\n")
	}
	if entry != "" {
		// The entry point's value is discarded, as Go's `func main` discards
		// it; its type is read off its own definition.
		rt := "void"
		if def, _, ok := strings.Cut(funcs[entry], " "+Name(entry)+"("); ok {
			rt = strings.TrimPrefix(def, "define internal ")
		}
		call := fmt.Sprintf("call %s %s()", rt, Name(entry))
		if rt != "void" {
			call = "%r = " + call
		}
		fmt.Fprintf(&b, "define void @main() #0 {\nentry:\n  %s\n  call void @ExitProcess(i32 0)\n  unreachable\n}\n\n", call)
	}
	// nounwind: nothing of ours unwinds (a crash is ExitProcess or a trap), so
	// no unwind tables. "no-builtins": no loop is rewritten into a call to the C
	// runtime's memset or memcpy, which this target does not link (llvm.md §2).
	b.WriteString("attributes #0 = { nounwind \"no-builtins\" }\n")
	return b.String()
}

// cbytes is a string's bytes in LLVM's c"…" notation: printable ASCII as
// itself, every other byte, `"` and `\` as \XX.
func cbytes(s string) string {
	var b strings.Builder
	for i := 0; i < len(s); i++ {
		c := s[i]
		if c >= 0x20 && c < 0x7f && c != '"' && c != '\\' {
			b.WriteByte(c)
		} else {
			fmt.Fprintf(&b, "\\%02X", c)
		}
	}
	return b.String()
}

type printer struct {
	tg      *emit.Target
	f       *ir.Func
	pl      *plan.Plan
	b       strings.Builder
	allocas []string
	slots   map[ir.V]string // a joined value's alloca
	names   map[ir.V]string // a value spelled other than %vN: a new table's pointer
	n       int
	err     error
}

func (p *printer) fail(format string, args ...any) {
	if p.err == nil {
		p.err = fmt.Errorf(format, args...)
	}
}

func (p *printer) line(format string, args ...any) {
	p.b.WriteString("  " + fmt.Sprintf(format, args...) + "\n")
}

func (p *printer) label(l string) { p.b.WriteString(l + ":\n") }

// fresh is a name the printer makes. It begins with `.`, which no IR value's
// name (%vN) and no template's (a stem, then `${#}`'s `.N`) does.
func (p *printer) fresh(stem string) string { p.n++; return fmt.Sprintf(".%s%d", stem, p.n) }

// ---------------------------------------------------------------- types

// llty is the LLVM type of a value of IR_P type t (llvm.md §3).
func (p *printer) llty(t string) string {
	switch {
	case t == "bool":
		return "i1"
	case t == "string", ir.ElemOf(p.tg, t) != "":
		return "ptr"
	}
	if _, _, ok := core.IntRangeBig(t); ok || core.UnboundedRange(t) {
		return "i64" // an integer held in the word, its range a fact
	}
	switch p.tg.ValueType(t) {
	case "int":
		return "i64"
	case "bool":
		return "i1"
	case "f64":
		return "double"
	case "string":
		return "ptr"
	}
	switch h := p.tg.HostType(t); h {
	case "i64", "i1", "double", "ptr":
		return h
	}
	p.fail("type %s has no LLVM type on target %s", t, p.tg.Name)
	return "i64"
}

func (p *printer) ty(v ir.V) string { return p.llty(p.f.Types[v]) }

// elem is a table's element type in memory: an i8 for a Boolean or a range
// the target holds in a byte, a double, a pointer for a table or a string, and
// the word otherwise (llvm.md §4). It is read off the table's representative,
// as ir/x86 reads it.
func (p *printer) elem(tab ir.V) (string, string) {
	t := p.f.Types[p.pl.Res(tab)]
	e := ir.ElemOf(p.tg, t)
	if e == "" {
		p.fail("%s is not a table", t)
		return "i64", ""
	}
	if e == "bool" || p.tg.ValueType(e) == "bool" {
		return "i8", e
	}
	if lo, hi, ok := core.IntRange(e); ok && p.tg.ReprBytes(lo, hi) == 1 {
		return "i8", e
	}
	return p.llty(e), e
}

// ---------------------------------------------------------------- values

// val is a value's spelling as an operand: its representative's register, a
// literal, or a zero.
func (p *printer) val(v ir.V) string {
	r := p.pl.Res(v)
	if s, ok := p.names[r]; ok {
		return s
	}
	if d := p.pl.Const[r]; d != nil {
		return p.lit(d, p.ty(r))
	}
	if p.pl.Zero[r] {
		switch p.ty(r) {
		case "ptr":
			return "null"
		case "i1":
			return "false"
		case "double":
			return "0.0"
		}
		return "0"
	}
	return fmt.Sprintf("%%v%d", r)
}

func (p *printer) typed(v ir.V) string { return p.ty(v) + " " + p.val(v) }

func (p *printer) lit(d *core.Term, ty string) string {
	switch d.Kind {
	case core.KBool:
		if d.IsTrue() {
			return "true"
		}
		return "false"
	case core.KStr:
		return p.str(d.Str)
	case core.KDec:
		f, _ := d.Dec.Float64()
		return fmt.Sprintf("0x%016X", math.Float64bits(f))
	case core.KInt:
		if ty == "double" {
			return fmt.Sprintf("0x%016X", math.Float64bits(float64(d.Int)))
		}
		return strconv.FormatInt(d.Int, 10)
	}
	if v, ok := new(big.Int).SetString(d.String(), 10); ok && v.IsInt64() {
		return v.String()
	}
	p.fail("literal %s has no LLVM spelling", core.ShowTerm(d))
	return "0"
}

// str is a string literal's global, a table of its UTF-8 bytes, one per
// distinct content in the module.
func (p *printer) str(s string) string {
	if n, ok := emit.LLVMStrings[s]; ok {
		return n
	}
	n := fmt.Sprintf("@.str.%d", len(emit.LLVMStrings))
	emit.LLVMStrings[s] = n
	return n
}

func (p *printer) slot(v ir.V) string {
	if s, ok := p.slots[v]; ok {
		return s
	}
	s := "%" + p.fresh("s")
	p.slots[v] = s
	p.allocas = append(p.allocas, fmt.Sprintf("  %s = alloca %s", s, p.ty(v)))
	return s
}

// load reads each joined value from its slot, where control arrives.
func (p *printer) load(vs []ir.V) {
	for _, v := range vs {
		p.line("%%v%d = load %s, ptr %s", v, p.ty(v), p.slot(v))
	}
}

// ---------------------------------------------------------------- the function

func (p *printer) function() string {
	var params []string
	for _, v := range p.f.Params {
		params = append(params, fmt.Sprintf("%s %%v%d", p.ty(v), v))
	}
	ret := p.retType()
	p.region(p.f.Body, exits{ret: true})
	var out strings.Builder
	fmt.Fprintf(&out, "define internal %s %s(%s) #0 {\nentry:\n", ret, Name(p.f.Name), strings.Join(params, ", "))
	for _, a := range p.allocas {
		out.WriteString(a + "\n")
	}
	out.WriteString(p.b.String())
	out.WriteString("}\n")
	return out.String()
}

func (p *printer) retType() string {
	switch len(p.f.Results) {
	case 0:
		return "void"
	case 1:
		return p.llty(p.f.Results[0])
	}
	var ts []string
	for _, t := range p.f.Results {
		ts = append(ts, p.llty(t))
	}
	return "{ " + strings.Join(ts, ", ") + " }"
}

func (p *printer) ret(args []ir.V) {
	switch len(args) {
	case 0:
		p.line("ret void")
	case 1:
		p.line("ret %s %s", p.llty(p.f.Results[0]), p.val(args[0]))
	default:
		rt := p.retType()
		acc := "undef"
		for i, a := range args {
			r := "%" + p.fresh("r")
			p.line("%s = insertvalue %s %s, %s %s, %d", r, rt, acc, p.llty(p.f.Results[i]), p.val(a), i)
			acc = r
		}
		p.line("ret %s %s", rt, acc)
	}
}

// ---------------------------------------------------------------- control

// target is where a yield, break or continue sends its arguments: the slots
// they are stored into and the block control passes to.
type target struct {
	slots []ir.V
	label string
}

// exits is what a region's terminators mean where it stands. A tabulate's
// body yields an element: stored at its index, then on to the next.
type exits struct {
	yield, brk, cont *target
	ret              bool
	tab              *tabulate
}

type tabulate struct {
	tab, idx ir.V
	next     string
}

func (p *printer) send(t *target, args []ir.V) {
	if t == nil {
		p.fail("a terminator with nowhere to go")
		return
	}
	for i, a := range args {
		p.line("store %s %s, ptr %s", p.ty(t.slots[i]), p.val(a), p.slot(t.slots[i]))
	}
	p.line("br label %%%s", t.label)
}

func (p *printer) region(r *ir.Region, x exits) {
	for i := range r.Stmts {
		p.stmt(&r.Stmts[i], x)
	}
	switch r.T {
	case ir.TYield:
		switch {
		case x.tab != nil:
			p.store(x.tab.tab, x.tab.idx, r.Args[0])
			p.line("br label %%%s", x.tab.next)
		case x.ret:
			p.ret(r.Args)
		default:
			p.send(x.yield, r.Args)
		}
	case ir.TBreak:
		p.send(x.brk, r.Args)
	case ir.TContinue:
		p.send(x.cont, r.Args)
	case ir.TBranch:
		if x.cont != nil && p.speculable(r.Then) && p.speculable(r.Else) {
			p.selects(r, x.cont)
			return
		}
		th, el := p.fresh("then"), p.fresh("else")
		p.line("br i1 %s, label %%%s, label %%%s", p.val(r.Cond), th, el)
		p.label(th)
		p.region(r.Then, x)
		p.label(el)
		p.region(r.Else, x)
	case ir.TUnreachable:
		p.line("unreachable")
	default:
		p.fail("terminator %s", r.T)
	}
}

// speculable reports an arm that goes round its loop computing only
// operations that are pure and have no undefined behaviour, only poison: so
// computing it when it is not taken changes nothing.
func (p *printer) speculable(r *ir.Region) bool {
	if r.T != ir.TContinue {
		return false
	}
	for i := range r.Stmts {
		s := &r.Stmts[i]
		switch s.Op {
		case ir.OConst, ir.OAdd, ir.OSub, ir.OMul, ir.ONeg, ir.OAnd, ir.OOr, ir.OXor, ir.ONot,
			ir.OEq, ir.ONe, ir.OLt, ir.OLe, ir.OGt, ir.OGe:
			if s.Mode == ir.MTrap {
				return false
			}
		default:
			return false
		}
	}
	return true
}

// selects prints a branch both of whose arms go round the loop as ONE back
// edge whose arguments are chosen (ADR 0080 item 2, backend-2026-10-26 §4):
// both arms computed, then a `select` per argument. Sound under poison, since
// `select` takes none from the operand it does not choose (LangRef), and the
// arms have no undefined behaviour to execute (speculable). Measured: the
// sieve's count of unmarked bytes, a branch that mispredicts on the primes'
// pattern, ran at 0.63 of MASM so and at 0.99 as a branch, which clang -O2 did
// not if-convert.
func (p *printer) selects(r *ir.Region, cont *target) {
	for _, arm := range []*ir.Region{r.Then, r.Else} {
		for i := range arm.Stmts {
			p.stmt(&arm.Stmts[i], exits{})
		}
	}
	for i := range r.Then.Args {
		ty := p.ty(cont.slots[i])
		a, b := p.val(r.Then.Args[i]), p.val(r.Else.Args[i])
		v := a
		if a != b {
			v = "%" + p.fresh("sel")
			p.line("%s = select i1 %s, %s %s, %s %s", v, p.val(r.Cond), ty, a, ty, b)
		}
		p.line("store %s %s, ptr %s", ty, v, p.slot(cont.slots[i]))
	}
	p.line("br label %%%s", cont.label)
}

// inner is the exits of a region an operation owns: its yield goes to the
// operation's results, a break or continue to the enclosing loop.
func inner(x exits, y *target) exits { return exits{yield: y, brk: x.brk, cont: x.cont} }

// ---------------------------------------------------------------- statements

func (p *printer) stmt(s *ir.Stmt, x exits) {
	switch s.Op {
	case ir.OConst, ir.OAssume, ir.OZero:
		// A literal is spelled where it is read; an assumption is the analyses'.
	case ir.OAdd, ir.OSub, ir.OMul, ir.ONeg, ir.ODiv, ir.ORem,
		ir.OAnd, ir.OOr, ir.OXor, ir.ONot, ir.OShl, ir.OShr, ir.OMod,
		ir.OEq, ir.ONe, ir.OLt, ir.OLe, ir.OGt, ir.OGe:
		p.op(s)
	case ir.OCall:
		p.call(s)
	case ir.OIndex:
		p.index(s)
	case ir.OLen:
		p.line("%%v%d = load i64, ptr %s", s.Res[0], p.val(s.Args[0]))
	case ir.OSet:
		p.store(s.Args[0], s.Args[1], s.Args[2])
	case ir.OIf:
		th, el, join := p.fresh("then"), p.fresh("else"), p.fresh("join")
		p.line("br i1 %s, label %%%s, label %%%s", p.val(s.Args[0]), th, el)
		y := &target{slots: s.Res, label: join}
		p.label(th)
		p.region(s.Sub[0], inner(x, y))
		p.label(el)
		p.region(s.Sub[1], inner(x, y))
		p.label(join)
		p.load(s.Res)
	case ir.OLoop:
		body := s.Sub[0]
		head, exit := p.fresh("head"), p.fresh("exit")
		for i, a := range s.Args {
			p.line("store %s %s, ptr %s", p.ty(body.Params[i]), p.val(a), p.slot(body.Params[i]))
		}
		p.line("br label %%%s", head)
		p.label(head)
		p.load(body.Params)
		p.region(body, exits{brk: &target{slots: s.Res, label: exit}, cont: &target{slots: body.Params, label: head}})
		p.label(exit)
		p.load(s.Res)
	case ir.OBuild:
		buf := s.Sub[0].Params[0]
		p.names[buf] = p.table(buf, p.val(s.Args[0]))
		done := p.fresh("built")
		p.region(s.Sub[0], inner(x, &target{slots: s.Res, label: done}))
		p.label(done)
		p.load(s.Res)
	case ir.OArray:
		t := p.table(s.Res[0], strconv.Itoa(len(s.Args)))
		p.names[s.Res[0]] = t
		for i, a := range s.Args {
			p.storeAt(s.Res[0], strconv.Itoa(i), a)
		}
	case ir.OTabulate:
		p.tabulate(s, x)
	default:
		p.fail("(%s …) is not printed on LLVM", s.Op)
	}
}

// op is an integer operation, spelled by the target's form for it (plan.Form),
// with the flags the IR proved (llvm.md §5).
func (p *printer) op(s *ir.Stmt) {
	form := p.pl.Form(s)
	f := form[0]
	if s.Mode == ir.MTrap {
		f = form[1]
	}
	if f == "" {
		p.fail("the target has no spelling for (%s %s)", s.Op, s.Mode)
		return
	}
	if s.Mode == ir.MExact && !NoFlags {
		f = p.flags(s, f)
	}
	p.expand(f, "expr", s.Res, s.Args)
}

// flags writes after an instruction's first word the flags the IR proved of
// this operation: `nsw`, the result inside the word, which is what `exact`
// means (ir.Decide); `nuw`, the same of the operands read as unsigned, from
// their proven ranges. `shl` takes them only where the bare instruction is the
// realization the IR chose, its count proven below 64 (ADR 0088). Only for the instruction that IS the operation: a form
// of several instructions (one naming its result) takes none.
func (p *printer) flags(s *ir.Stmt, f string) string {
	if holes(f)['r'] {
		return f
	}
	word, rest, ok := strings.Cut(f, " ")
	if !ok {
		return f
	}
	want := map[ir.Op]string{ir.OAdd: "add", ir.OSub: "sub", ir.OMul: "mul", ir.ONeg: "sub", ir.OShl: "shl"}[s.Op]
	if want == "" || word != want {
		return f
	}
	fl := "nsw"
	if plantNuwFault {
		return word + " nuw nsw " + rest
	}
	switch s.Op {
	case ir.OAdd, ir.OMul:
		if p.lo(s.Args[0]) >= 0 && p.lo(s.Args[1]) >= 0 {
			fl = "nuw nsw"
		}
	case ir.OShl:
		// a·2ᵏ inside the word with a ≥ 0 shifts out no set bit.
		if p.lo(s.Args[0]) >= 0 {
			fl = "nuw nsw"
		}
	case ir.OSub:
		// a − b leaves no unsigned wrap when 0 ≤ b ≤ a.
		if p.lo(s.Args[1]) >= 0 && p.lo(s.Args[0]) >= p.hi(s.Args[1]) {
			fl = "nuw nsw"
		}
	}
	return word + " " + fl + " " + rest
}

// lo and hi are a value's proven ends, from its IR_P type, ±∞ when unbounded.
func (p *printer) lo(v ir.V) float64 {
	if lo, _, ok := core.IntRangeBig(p.f.Types[v]); ok && lo != nil {
		f, _ := new(big.Float).SetInt(lo).Float64()
		return f
	}
	if d := p.pl.Const[p.pl.Res(v)]; d != nil && d.Kind == core.KInt {
		return float64(d.Int)
	}
	return math.Inf(-1)
}

func (p *printer) hi(v ir.V) float64 {
	if _, hi, ok := core.IntRangeBig(p.f.Types[v]); ok && hi != nil {
		f, _ := new(big.Float).SetInt(hi).Float64()
		return f
	}
	if d := p.pl.Const[p.pl.Res(v)]; d != nil && d.Kind == core.KInt {
		return float64(d.Int)
	}
	return math.Inf(1)
}

func (p *printer) call(s *ir.Stmt) {
	q, ok := p.tg.Prims[s.Name]
	if !ok || (q.Kind != "expr" && q.Kind != "stmt") {
		p.fail("(call %s) has no template on target %s", s.Name, p.tg.Name)
		return
	}
	if q.Form == "" {
		p.fail("(call %s) is realized by a term, which reached the printer unsubstituted (ir.RealizeOps)", s.Name)
		return
	}
	p.imports(q)
	if len(s.Res) > 1 && q.Kind != "stmt" {
		// A HOST OPERATION INTO A PRODUCT B₁ × … × Bₙ answers LLVM's aggregate
		// { ρB₁, …, ρBₙ }, and each result is its projection: extractvalue j,
		// the product's universal property.
		var ts []string
		for _, v := range s.Res {
			ts = append(ts, p.ty(v))
		}
		agg := "%" + p.fresh("agg")
		ty := "{ " + strings.Join(ts, ", ") + " }"
		text := p.fill(q.Form, agg, s.Args)
		if holes(q.Form)['r'] {
			p.lines(text)
		} else {
			p.line("%s = %s", agg, text)
		}
		for j, v := range s.Res {
			p.line("%%v%d = extractvalue %s %s, %d", v, ty, agg, j)
		}
		return
	}
	p.expand(q.Form, q.Kind, s.Res, s.Args)
}

func (p *printer) imports(q emit.Prim) {
	if q.Import != "" {
		emit.LLVMImports[q.Import] = true
	}
	for _, x := range q.Externs {
		emit.LLVMImports[x] = true
	}
	if q.Lib != "" {
		emit.LLVMLibs[q.Lib] = true
	}
}

// expand prints one template (llvm.md §6). An expression's template is its
// instruction's right-hand side, unless it names its result, when it is the
// instructions themselves; a statement's is its instructions, and its value is
// its first argument (plan's alias).
func (p *printer) expand(form, kind string, res, args []ir.V) {
	dst := ""
	if kind != "stmt" && len(res) == 1 {
		dst = fmt.Sprintf("%%v%d", res[0])
	}
	text := p.fill(form, dst, args)
	if kind != "stmt" && !holes(form)['r'] {
		if dst == "" {
			p.fail("an expression template with no result")
			return
		}
		p.line("%s = %s", dst, text)
		return
	}
	p.lines(text)
}

// lines prints a filled template of several instructions, a label as a label.
func (p *printer) lines(text string) {
	for _, l := range strings.Split(text, "\n") {
		l = strings.TrimSpace(l)
		switch {
		case l == "":
		case strings.HasSuffix(l, ":") && !strings.ContainsAny(l, " ="):
			p.label(strings.TrimSuffix(l, ":"))
		default:
			p.line("%s", l)
		}
	}
}

// holes reports which kinds of hole a template has: 'r' its result.
func holes(form string) map[byte]bool {
	out := map[byte]bool{}
	for i := 0; i+1 < len(form); i++ {
		if form[i] != '%' {
			continue
		}
		i++
		out[form[i]] = true
	}
	return out
}

// fill expands a template's holes (core/jreadtarget.go's numbered holes): `%%`
// a `%`; `%r` the result; `%u` the expansion's number, `.N`; `%N` and `%{N}`
// operand N typed, `i64 %v3`; `%vN` its value alone.
func (p *printer) fill(form, dst string, args []ir.V) string {
	p.n++
	u := fmt.Sprintf(".%d", p.n)
	var b strings.Builder
	operand := func(i int) (int, int, bool) { // the operand number at form[i:], and its length
		if i < len(form) && form[i] == '{' {
			j := strings.IndexByte(form[i:], '}')
			if j < 0 {
				return 0, 0, false
			}
			n, err := strconv.Atoi(form[i+1 : i+j])
			return n, j + 1, err == nil
		}
		if i < len(form) && form[i] >= '1' && form[i] <= '9' {
			return int(form[i] - '0'), 1, true
		}
		return 0, 0, false
	}
	pick := func(n int) (ir.V, bool) {
		if n < 1 || n > len(args) {
			p.fail("template %q names operand %d of %d", form, n, len(args))
			return 0, false
		}
		return args[n-1], true
	}
	next := 0
	for i := 0; i < len(form); i++ {
		if form[i] != '%' || i+1 >= len(form) {
			b.WriteByte(form[i])
			continue
		}
		i++
		switch c := form[i]; {
		case c == '%':
			b.WriteByte('%')
		case c == 'r':
			b.WriteString(dst)
		case c == 'u':
			b.WriteString(u)
		case c == 's':
			if v, ok := pick(next + 1); ok {
				b.WriteString(p.typed(v))
			}
			next++
		case c == 'v':
			if n, w, ok := operand(i + 1); ok {
				if v, ok := pick(n); ok {
					b.WriteString(p.val(v))
				}
				i += w
			} else {
				p.fail("template %q: %%v names no operand", form)
			}
		default:
			if n, w, ok := operand(i); ok {
				if v, ok := pick(n); ok {
					b.WriteString(p.typed(v))
				}
				i += w - 1
			} else {
				p.fail("template %q: %%%c is not a hole on LLVM", form, c)
			}
		}
	}
	return b.String()
}

// ---------------------------------------------------------------- tables

// table allocates a table of n elements for v's type through the target's
// allocator (emit.FindAlloc), zero on creation, and writes its length.
func (p *printer) table(v ir.V, n string) string {
	q, ok := p.tg.FindAlloc()
	if !ok {
		p.fail("this target declares no allocator, so a table has no memory (docs/spec/tables.md §10)")
		return "null"
	}
	p.imports(q)
	et, _ := p.elem(v)
	w := map[string]int{"i8": 1, "i1": 1}[et]
	if w == 0 {
		w = 8
	}
	bytes := "%" + p.fresh("n")
	p.line("%s = mul i64 %s, %d", bytes, n, w)
	total := "%" + p.fresh("n")
	p.line("%s = add i64 %s, 8", total, bytes)
	t := "%" + p.fresh("t")
	for _, l := range strings.Split(p.fillRaw(q.Form, t, "i64 "+total), "\n") {
		l = strings.TrimSpace(l)
		switch {
		case l == "":
		case strings.HasSuffix(l, ":") && !strings.ContainsAny(l, " ="):
			p.label(strings.TrimSuffix(l, ":"))
		case !holes(q.Form)['r']:
			p.line("%s = %s", t, l)
		default:
			p.line("%s", l)
		}
	}
	p.line("store i64 %s, ptr %s", n, t)
	return t
}

// fillRaw fills a template whose one operand is already spelled.
func (p *printer) fillRaw(form, dst, op string) string {
	p.n++
	u := fmt.Sprintf(".%d", p.n)
	r := strings.NewReplacer("%%", "%", "%r", dst, "%u", u, "%v1", strings.TrimPrefix(op, "i64 "), "%1", op, "%s", op)
	return r.Replace(form)
}

// addr is the element i's address: past the 8-byte length, then i elements
// of the table's width. `inbounds` is the index's obligation, 0 ≤ i < len t,
// which the IR proved (refinements.md §3a: `-checked` never clears it).
func (p *printer) addr(tab ir.V, i, et string) string {
	d := "%" + p.fresh("d")
	inb := " inbounds"
	if NoFlags {
		inb = ""
	}
	p.line("%s = getelementptr%s i8, ptr %s, i64 8", d, inb, p.val(tab))
	e := "%" + p.fresh("e")
	p.line("%s = getelementptr%s %s, ptr %s, i64 %s", e, inb, et, d, i)
	return e
}

func (p *printer) index(s *ir.Stmt) {
	et, _ := p.elem(s.Args[0])
	e := p.addr(s.Args[0], p.val(s.Args[1]), et)
	res := fmt.Sprintf("%%v%d", s.Res[0])
	if et != "i8" {
		p.line("%s = load %s, ptr %s", res, et, e)
		return
	}
	b := "%" + p.fresh("b")
	p.line("%s = load i8, ptr %s", b, e)
	if p.ty(s.Res[0]) == "i1" {
		p.line("%s = icmp ne i8 %s, 0", res, b)
	} else {
		p.line("%s = zext i8 %s to i64", res, b)
	}
}

func (p *printer) store(tab, i, v ir.V) { p.storeAt(tab, p.val(i), v) }

// storeAt writes one element. A narrow one is narrowed: a Boolean widened to
// its byte, an integer truncated, exactly, since it is proven in the
// element's range.
func (p *printer) storeAt(tab ir.V, i string, v ir.V) {
	et, _ := p.elem(tab)
	e := p.addr(tab, i, et)
	x := p.val(v)
	if et == "i8" {
		z := "%" + p.fresh("z")
		if p.ty(v) == "i1" {
			p.line("%s = zext i1 %s to i8", z, x)
		} else {
			p.line("%s = trunc i64 %s to i8", z, x)
		}
		x = z
	}
	p.line("store %s %s, ptr %s", et, x, e)
}

// tabulate is a rule's table: allocated, then each element stored by a loop
// over its indices, the body's yield its value.
func (p *printer) tabulate(s *ir.Stmt, x exits) {
	res, n, i := s.Res[0], s.Args[0], s.Sub[0].Params[0]
	t := p.table(res, p.val(n))
	p.names[res] = t
	head, body, next, done := p.fresh("tab"), p.fresh("tabbody"), p.fresh("tabnext"), p.fresh("tabdone")
	p.line("store i64 0, ptr %s", p.slot(i))
	p.line("br label %%%s", head)
	p.label(head)
	p.load([]ir.V{i})
	c := "%" + p.fresh("c")
	p.line("%s = icmp slt i64 %%v%d, %s", c, i, p.val(n))
	p.line("br i1 %s, label %%%s, label %%%s", c, body, done)
	p.label(body)
	p.region(s.Sub[0], exits{brk: x.brk, cont: x.cont, tab: &tabulate{tab: res, idx: i, next: next}})
	p.label(next)
	k := "%" + p.fresh("k")
	p.line("%s = add nuw nsw i64 %%v%d, 1", k, i)
	p.line("store i64 %s, ptr %s", k, p.slot(i))
	p.line("br label %%%s", head)
	p.label(done)
}
